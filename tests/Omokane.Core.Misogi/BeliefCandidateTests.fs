module BeliefCandidateTests

open System
open Expecto
open Omokane.Core.Domain

let private 観測者A = エンティティID "observer.belief.a"
let private 観測者B = エンティティID "observer.belief.b"

let private 感知値を作る 観測者 信号ID 種別 確信度 Tick : 感知値 =
    {
        観測者ID = 観測者
        信号ID = 伝播信号ID 信号ID
        種別 = 種別
        測定値 = 1.0
        確信度 = 確信度
        Tick = Tick
    }

let private 観測を作る 観測者 概要 確信度 Tick 種別 : 観測 =
    {
        観測者ID = 観測者
        概要 = 概要
        確信度 = 確信度
        根拠一覧 = [ 感知値を作る 観測者 (概要 + ".signal") 種別 確信度 Tick ]
    }

let private 候補を得る = function
    | Ok 候補 -> 候補
    | Error エラー一覧 -> failtestf "信念候補生成が失敗しました: %A" エラー一覧

let private エラー一覧を得る = function
    | Error エラー一覧 -> エラー一覧
    | Ok 候補 -> failtestf "エラーを期待しましたが成功しました: %A" 候補

let private エラー一覧を確認する 期待値 結果 =
    結果
    |> エラー一覧を得る
    |> fun 実際値 -> Expect.equal 実際値 期待値 "エラー一覧が固定順である"

[<Tests>]
let 全テスト =
    testList
        "観測から信念候補を作る"
        [
            testCase "1件の根拠観測から候補を生成できる" <| fun _ ->
                let 根拠 = 観測を作る 観測者A "煙を観測" 0.8 10L 視覚
                let 候補 = 信念候補生成.観測から作る "火災がある" 0.5 [ 根拠 ] [] |> 候補を得る

                Expect.equal 候補.仮説 "火災がある" "明示された仮説を保存する"
                Expect.equal 候補.根拠一覧 [ 根拠 ] "根拠観測を保存する"

            testCase "根拠確信度1と事前確率0.5から確率0.75になる" <| fun _ ->
                let 根拠 = 観測を作る 観測者A "強い根拠" 1.0 10L 視覚
                let 候補 = 信念候補生成.観測から作る "仮説" 0.5 [ 根拠 ] [] |> 候補を得る

                Expect.equal 候補.確率 0.75 "根拠を軟証拠として加える"

            testCase "反証確信度1と事前確率0.5から確率0.25になる" <| fun _ ->
                let 反証 = 観測を作る 観測者A "強い反証" 1.0 10L 視覚
                let 候補 = 信念候補生成.観測から作る "仮説" 0.5 [] [ 反証 ] |> 候補を得る

                Expect.equal 候補.確率 0.25 "反証を分母へ加える"

            testCase "同量の根拠と反証で事前確率0.5へ戻る" <| fun _ ->
                let 根拠 = 観測を作る 観測者A "根拠" 1.0 10L 視覚
                let 反証 = 観測を作る 観測者A "反証" 1.0 11L 聴覚
                let 候補 = 信念候補生成.観測から作る "仮説" 0.5 [ 根拠 ] [ 反証 ] |> 候補を得る

                Expect.equal 候補.確率 0.5 "同量の根拠と反証を釣り合わせる"

            testCase "複数の根拠と反証を式どおり集約する" <| fun _ ->
                let 根拠一覧 =
                    [
                        観測を作る 観測者A "根拠1" 0.6 10L 視覚
                        観測を作る 観測者A "根拠2" 0.4 11L 聴覚
                    ]

                let 反証一覧 =
                    [
                        観測を作る 観測者A "反証1" 0.25 12L 嗅覚
                        観測を作る 観測者A "反証2" 0.75 13L 地盤感知
                    ]

                let 候補 = 信念候補生成.観測から作る "仮説" 0.25 根拠一覧 反証一覧 |> 候補を得る

                Expect.equal 候補.確率 (1.25 / 3.0) "指定式で複数観測を集約する"

            testCase "確信度0の根拠は確率へ影響しない" <| fun _ ->
                let 根拠 = 観測を作る 観測者A "影響なし" 0.0 10L 視覚
                let 候補 = 信念候補生成.観測から作る "仮説" 0.4 [ 根拠 ] [] |> 候補を得る

                Expect.equal 候補.確率 0.4 "証拠量0として扱う"

            testCase "確信度0の反証は確率へ影響しない" <| fun _ ->
                let 反証 = 観測を作る 観測者A "影響なし" 0.0 10L 視覚
                let 候補 = 信念候補生成.観測から作る "仮説" 0.4 [] [ 反証 ] |> 候補を得る

                Expect.equal 候補.確率 0.4 "反証量0として扱う"

            testCase "根拠だけでも生成できる" <| fun _ ->
                let 根拠 = 観測を作る 観測者A "根拠" 0.5 10L 視覚
                信念候補生成.観測から作る "仮説" 0.5 [ 根拠 ] [] |> 候補を得る |> ignore

            testCase "反証だけでも生成できる" <| fun _ ->
                let 反証 = 観測を作る 観測者A "反証" 0.5 10L 視覚
                信念候補生成.観測から作る "仮説" 0.5 [] [ 反証 ] |> 候補を得る |> ignore

            testCase "根拠と反証が両方空なら拒否する" <| fun _ ->
                信念候補生成.観測から作る "仮説" 0.5 [] []
                |> エラー一覧を確認する [ "信念候補生成に使用する観測一覧が空です。" ]

            testCase "空白の仮説を拒否する" <| fun _ ->
                let 根拠 = 観測を作る 観測者A "根拠" 0.5 10L 視覚

                信念候補生成.観測から作る "  " 0.5 [ 根拠 ] []
                |> エラー一覧を確認する [ "信念候補生成の仮説が空です。" ]

            testCase "事前確率のNaNとInfinityを拒否する" <| fun _ ->
                let 根拠 = 観測を作る 観測者A "根拠" 0.5 10L 視覚

                信念候補生成.観測から作る "仮説" Double.NaN [ 根拠 ] []
                |> エラー一覧を確認する [ "信念候補生成の事前確率が有限値ではありません。" ]

                信念候補生成.観測から作る "仮説" Double.PositiveInfinity [ 根拠 ] []
                |> エラー一覧を確認する
                    [
                        "信念候補生成の事前確率が有限値ではありません。"
                        "信念候補生成の事前確率は0.0以上1.0以下である必要があります。"
                    ]

            testCase "事前確率の範囲外を拒否する" <| fun _ ->
                let 根拠 = 観測を作る 観測者A "根拠" 0.5 10L 視覚

                信念候補生成.観測から作る "仮説" -0.1 [ 根拠 ] []
                |> エラー一覧を確認する [ "信念候補生成の事前確率は0.0以上1.0以下である必要があります。" ]

                信念候補生成.観測から作る "仮説" 1.1 [ 根拠 ] []
                |> エラー一覧を確認する [ "信念候補生成の事前確率は0.0以上1.0以下である必要があります。" ]

            testCase "0と1の事前確率を許可する" <| fun _ ->
                let 観測 = 観測を作る 観測者A "影響なし" 0.0 10L 視覚
                let 下限 = 信念候補生成.観測から作る "下限" 0.0 [ 観測 ] [] |> 候補を得る
                let 上限 = 信念候補生成.観測から作る "上限" 1.0 [ 観測 ] [] |> 候補を得る

                Expect.equal 下限.確率 0.0 "事前確率0を許可する"
                Expect.equal 上限.確率 1.0 "事前確率1を許可する"

            testCase "不正な根拠観測へindex付きエラーを返す" <| fun _ ->
                let 正常 = 観測を作る 観測者A "正常" 0.5 10L 視覚
                let 不正 = { 観測を作る 観測者A "不正" 0.5 10L 視覚 with 概要 = "" }

                信念候補生成.観測から作る "仮説" 0.5 [ 正常; 不正 ] []
                |> エラー一覧を確認する [ "根拠観測[1]: 観測の概要が空です。" ]

            testCase "不正な反証観測へindex付きエラーを返す" <| fun _ ->
                let 不正 =
                    { 観測を作る 観測者A "不正" 0.5 10L 視覚 with 確信度 = Double.NaN }

                信念候補生成.観測から作る "仮説" 0.5 [] [ 不正 ]
                |> エラー一覧を確認する [ "反証観測[0]: 観測の確信度が有限値ではありません。" ]

            testCase "根拠エラーを反証エラーより先に返す" <| fun _ ->
                let 不正根拠 =
                    {
                        観測を作る 観測者A "不正根拠" 0.5 10L 視覚 with
                            概要 = ""
                            確信度 = -0.1
                    }

                let 不正反証 =
                    { 観測を作る 観測者A "不正反証" 0.5 10L 視覚 with 確信度 = Double.NaN }

                信念候補生成.観測から作る "仮説" 0.5 [ 不正根拠 ] [ 不正反証 ]
                |> エラー一覧を確認する
                    [
                        "根拠観測[0]: 観測の概要が空です。"
                        "根拠観測[0]: 観測の確信度は0.0以上1.0以下である必要があります。"
                        "反証観測[0]: 観測の確信度が有限値ではありません。"
                    ]

            testCase "観測者ID不一致を拒否する" <| fun _ ->
                let 根拠 = 観測を作る 観測者A "根拠" 0.5 10L 視覚
                let 反証 = 観測を作る 観測者B "反証" 0.5 10L 視覚

                信念候補生成.観測から作る "仮説" 0.5 [ 根拠 ] [ 反証 ]
                |> エラー一覧を確認する [ "信念候補生成に使用する観測の観測者IDが一致しません。" ]

            testCase "異なるTickの観測を統合できる" <| fun _ ->
                let 第一 = 観測を作る 観測者A "Tick10" 0.5 10L 視覚
                let 第二 = 観測を作る 観測者A "Tick20" 0.5 20L 視覚

                信念候補生成.観測から作る "仮説" 0.5 [ 第一; 第二 ] [] |> 候補を得る |> ignore

            testCase "異なる感知種別の観測を統合できる" <| fun _ ->
                let 視覚観測 = 観測を作る 観測者A "視覚" 0.5 10L 視覚
                let 嗅覚観測 = 観測を作る 観測者A "嗅覚" 0.5 10L 嗅覚

                信念候補生成.観測から作る "仮説" 0.5 [ 視覚観測; 嗅覚観測 ] []
                |> 候補を得る
                |> ignore

            testCase "根拠一覧の入力順を維持する" <| fun _ ->
                let 第一 = 観測を作る 観測者A "第一" 0.5 10L 視覚
                let 第二 = 観測を作る 観測者A "第二" 0.5 11L 聴覚
                let 入力 = [ 第二; 第一 ]
                let 候補 = 信念候補生成.観測から作る "仮説" 0.5 入力 [] |> 候補を得る

                Expect.equal 候補.根拠一覧 入力 "根拠を並べ替えない"

            testCase "反証一覧の入力順を維持する" <| fun _ ->
                let 第一 = 観測を作る 観測者A "第一" 0.5 10L 視覚
                let 第二 = 観測を作る 観測者A "第二" 0.5 11L 聴覚
                let 入力 = [ 第二; 第一 ]
                let 候補 = 信念候補生成.観測から作る "仮説" 0.5 [] 入力 |> 候補を得る

                Expect.equal 候補.反証一覧 入力 "反証を並べ替えない"

            testCase "入力値を変更しない" <| fun _ ->
                let 根拠 = [ 観測を作る 観測者A "根拠" 0.7 10L 視覚 ]
                let 反証 = [ 観測を作る 観測者A "反証" 0.2 11L 聴覚 ]
                let 根拠前 = 根拠
                let 反証前 = 反証

                信念候補生成.観測から作る "仮説" 0.5 根拠 反証 |> ignore

                Expect.equal 根拠 根拠前 "根拠入力を変更しない"
                Expect.equal 反証 反証前 "反証入力を変更しない"

            testCase "同じ入力から同じ結果を返す" <| fun _ ->
                let 根拠 = [ 観測を作る 観測者A "根拠" 0.7 10L 視覚 ]
                let 反証 = [ 観測を作る 観測者A "反証" 0.2 11L 聴覚 ]
                let 第一 = 信念候補生成.観測から作る "仮説" 0.5 根拠 反証
                let 第二 = 信念候補生成.観測から作る "仮説" 0.5 根拠 反証

                Expect.equal 第一 第二 "構造的に同じ結果を返す"

            testCase "生成候補が既存の信念候補検証を通る" <| fun _ ->
                let 根拠 = 観測を作る 観測者A "根拠" 0.7 10L 視覚
                let 候補 = 信念候補生成.観測から作る "仮説" 0.5 [ 根拠 ] [] |> 候補を得る

                Expect.equal (観測検証.信念候補を検証する 候補) (Ok ()) "既存契約に適合する"

            testCase "同一観測の重複を入力回数どおり集約する" <| fun _ ->
                let 根拠 = 観測を作る 観測者A "重複根拠" 0.5 10L 視覚
                let 候補 = 信念候補生成.観測から作る "仮説" 0.5 [ 根拠; 根拠 ] [] |> 候補を得る

                Expect.equal 候補.確率 0.75 "同一観測を2回分の証拠量として扱う"
                Expect.equal 候補.根拠一覧 [ 根拠; 根拠 ] "重複排除しない"

            testCase "伝播信号から感知値と観測を経て信念候補まで接続できる" <| fun _ ->
                let 設定: 感知設定 =
                    {
                        種別 = 地盤感知
                        対象量種別 = 地盤振動
                        対象媒体 = 地盤
                        最大距離 = 10.0
                        感度倍率 = 1.0
                        感知閾値 = 0.0
                        確信飽和値 = 10.0
                    }

                let 信号を作る ID 強度: 伝播信号 =
                    {
                        ID = 伝播信号ID ID
                        原因因果ID = None
                        発生源EntityID = None
                        量種別 = 地盤振動
                        媒体 = 地盤
                        発生位置 = { X = 0.0; Y = 0.0 }
                        方向 = None
                        強度 = 強度
                        方式 = 波動
                        寿命Tick = 1L
                    }

                let 感知する (信号: 伝播信号) =
                    match 感知値生成.伝播信号から作る 30L 観測者A 信号.発生位置 設定 信号 with
                    | Ok(Some 感知) -> 感知
                    | 結果 -> failtestf "感知値生成に失敗しました: %A" 結果

                let 観測する 概要 感知 =
                    match 観測生成.感知値から観測を作る 概要 [ 感知 ] with
                    | Ok 対象観測 -> 対象観測
                    | Error エラー一覧 -> failtestf "観測生成に失敗しました: %A" エラー一覧

                let 根拠 = 信号を作る "signal.evidence" 8.0 |> 感知する |> 観測する "強い振動"
                let 反証 = 信号を作る "signal.counter" 2.0 |> 感知する |> 観測する "弱い反証"
                let 候補 = 信念候補生成.観測から作る "大型Entityが接近中" 0.5 [ 根拠 ] [ 反証 ] |> 候補を得る

                Expect.equal 候補.根拠一覧 [ 根拠 ] "標準認識経路の根拠を保存する"
                Expect.equal 候補.反証一覧 [ 反証 ] "標準認識経路の反証を保存する"
                Expect.equal 候補.確率 (1.3 / 2.0) "感知確信度を軟証拠として集約する"
        ]
