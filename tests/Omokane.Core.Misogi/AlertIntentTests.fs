module AlertIntentTests

open System
open Expecto
open Omokane.Core.Domain

let private 観測者A = エンティティID "observer.alert.a"
let private 観測者B = エンティティID "observer.alert.b"

let private 感知値を作る 観測者 信号ID 種別 確信度 Tick : 感知値 =
    {
        観測者ID = 観測者
        信号ID = 伝播信号ID 信号ID
        種別 = 種別
        測定値 = 1.0
        確信度 = 確信度
        Tick = Tick
    }

let private 観測を作る 観測者 概要 確信度 Tick 種別 : 観測 =
    {
        観測者ID = 観測者
        概要 = 概要
        確信度 = 確信度
        根拠一覧 = [ 感知値を作る 観測者 (概要 + ".signal") 種別 確信度 Tick ]
    }

let private 候補を作る 確率 根拠一覧 反証一覧 : 信念候補 =
    {
        仮説 = "大型Entityが接近中"
        確率 = 確率
        根拠一覧 = 根拠一覧
        反証一覧 = 反証一覧
    }

let private 基本観測 = 観測を作る 観測者A "振動を観測" 0.8 10L 地盤感知
let private 基本候補 = 候補を作る 0.8 [ 基本観測 ] []
let private 基本設定: 警戒意図設定 = { 発生閾値 = 0.6 }

let private 意図を得る = function
    | Ok(Some 意図) -> 意図
    | Ok None -> failtest "警戒意図成立を期待しましたが不成立でした。"
    | Error エラー一覧 -> failtestf "警戒意図生成が失敗しました: %A" エラー一覧

let private エラー一覧を得る = function
    | Error エラー一覧 -> エラー一覧
    | Ok 結果 -> failtestf "エラーを期待しましたが成功しました: %A" 結果

let private エラー一覧を確認する 期待値 結果 =
    結果
    |> エラー一覧を得る
    |> fun 実際値 -> Expect.equal 実際値 期待値 "エラー一覧が固定順である"

[<Tests>]
let 全テスト =
    testList
        "信念候補から警戒意図を作る"
        [
            testCase "閾値を超えた信念候補から警戒意図を生成できる" <| fun _ ->
                警戒意図生成.信念候補から作る 基本設定 基本候補 |> 意図を得る |> ignore

            testCase "閾値未満はOk Noneになる" <| fun _ ->
                let 候補 = { 基本候補 with 確率 = 0.5 }
                Expect.equal (警戒意図生成.信念候補から作る 基本設定 候補) (Ok None) "正常な不成立を返す"

            testCase "閾値と等しい確率は意図成立になる" <| fun _ ->
                let 候補 = { 基本候補 with 確率 = 0.6 }
                警戒意図生成.信念候補から作る 基本設定 候補 |> 意図を得る |> ignore

            testCase "不成立はErrorではない" <| fun _ ->
                let 候補 = { 基本候補 with 確率 = 0.0 }

                match 警戒意図生成.信念候補から作る 基本設定 候補 with
                | Ok None -> ()
                | 結果 -> failtestf "Ok Noneを期待しました: %A" 結果

            testCase "発生閾値0を許可する" <| fun _ ->
                let 設定: 警戒意図設定 = { 発生閾値 = 0.0 }
                let 候補 = { 基本候補 with 確率 = 0.0 }
                警戒意図生成.信念候補から作る 設定 候補 |> 意図を得る |> ignore

            testCase "発生閾値1を許可する" <| fun _ ->
                let 設定: 警戒意図設定 = { 発生閾値 = 1.0 }
                let 候補 = { 基本候補 with 確率 = 1.0 }
                警戒意図生成.信念候補から作る 設定 候補 |> 意図を得る |> ignore

            testCase "閾値のNaNとInfinityを拒否する" <| fun _ ->
                警戒意図設定.検証する { 発生閾値 = Double.NaN }
                |> エラー一覧を確認する [ "警戒意図設定の発生閾値が有限値ではありません。" ]

                警戒意図設定.検証する { 発生閾値 = Double.PositiveInfinity }
                |> エラー一覧を確認する
                    [
                        "警戒意図設定の発生閾値が有限値ではありません。"
                        "警戒意図設定の発生閾値は0.0以上1.0以下である必要があります。"
                    ]

            testCase "閾値の範囲外を拒否する" <| fun _ ->
                警戒意図設定.検証する { 発生閾値 = -0.1 }
                |> エラー一覧を確認する [ "警戒意図設定の発生閾値は0.0以上1.0以下である必要があります。" ]

                警戒意図設定.検証する { 発生閾値 = 1.1 }
                |> エラー一覧を確認する [ "警戒意図設定の発生閾値は0.0以上1.0以下である必要があります。" ]

            testCase "観測者IDを最初の根拠観測から導出する" <| fun _ ->
                let 意図 = 警戒意図生成.信念候補から作る 基本設定 基本候補 |> 意図を得る
                Expect.equal 意図.観測者ID 観測者A "最初の根拠観測を使う"

            testCase "根拠なしでは最初の反証観測から観測者IDを導出する" <| fun _ ->
                let 反証 = 観測を作る 観測者A "反証" 0.2 11L 聴覚
                let 候補 = 候補を作る 0.8 [] [ 反証 ]
                let 意図 = 警戒意図生成.信念候補から作る 基本設定 候補 |> 意図を得る
                Expect.equal 意図.観測者ID 観測者A "最初の反証観測を使う"

            testCase "対象仮説を候補から保存する" <| fun _ ->
                let 候補 = { 基本候補 with 仮説 = "森に危険がある" }
                let 意図 = 警戒意図生成.信念候補から作る 基本設定 候補 |> 意図を得る
                Expect.equal 意図.対象仮説 候補.仮説 "仮説を変更しない"

            testCase "警戒度が候補確率と完全に一致する" <| fun _ ->
                let 候補 = { 基本候補 with 確率 = 0.625 }
                let 意図 = 警戒意図生成.信念候補から作る 基本設定 候補 |> 意図を得る
                Expect.equal 意図.警戒度 候補.確率 "再正規化しない"

            testCase "由来信念候補を構造的に保存する" <| fun _ ->
                let 意図 = 警戒意図生成.信念候補から作る 基本設定 基本候補 |> 意図を得る
                Expect.equal 意図.由来信念候補 基本候補 "入力候補をそのまま保存する"

            testCase "根拠と反証が両方空の候補を拒否する" <| fun _ ->
                let 候補 = 候補を作る 0.8 [] []
                警戒意図生成.信念候補から作る 基本設定 候補
                |> エラー一覧を確認する [ "警戒意図生成に使用する観測一覧が空です。" ]

            testCase "空白の観測者IDを拒否する" <| fun _ ->
                let 正常観測 = 観測を作る 観測者A "正常" 0.8 10L 視覚
                let 空白ID観測 = 観測を作る (エンティティID "  ") "空白ID" 0.2 11L 聴覚
                let 候補 = 候補を作る 0.8 [ 正常観測 ] [ 空白ID観測 ]
                警戒意図生成.信念候補から作る 基本設定 候補
                |> エラー一覧を確認する
                    [
                        "警戒意図生成に使用する観測者IDが空です。"
                        "警戒意図生成に使用する観測の観測者IDが一致しません。"
                    ]

            testCase "観測者ID不一致を拒否する" <| fun _ ->
                let 根拠 = 観測を作る 観測者A "根拠" 0.8 10L 視覚
                let 反証 = 観測を作る 観測者B "反証" 0.2 11L 聴覚
                let 候補 = 候補を作る 0.8 [ 根拠 ] [ 反証 ]
                警戒意図生成.信念候補から作る 基本設定 候補
                |> エラー一覧を確認する [ "警戒意図生成に使用する観測の観測者IDが一致しません。" ]

            testCase "不正な信念候補へ接頭辞付きエラーを返す" <| fun _ ->
                let 候補 = { 基本候補 with 仮説 = ""; 確率 = -0.1 }
                警戒意図生成.信念候補から作る 基本設定 候補
                |> エラー一覧を確認する
                    [
                        "信念候補: 信念候補の仮説が空です。"
                        "信念候補: 信念候補の確率は0.0以上1.0以下である必要があります。"
                    ]

            testCase "不正な根拠観測へindex付きエラーを返す" <| fun _ ->
                let 正常 = 観測を作る 観測者A "正常" 0.8 10L 視覚
                let 不正 = { 観測を作る 観測者A "不正" 0.8 10L 視覚 with 概要 = "" }
                let 候補 = 候補を作る 0.8 [ 正常; 不正 ] []
                警戒意図生成.信念候補から作る 基本設定 候補
                |> エラー一覧を確認する [ "根拠観測[1]: 観測の概要が空です。" ]

            testCase "不正な反証観測へindex付きエラーを返す" <| fun _ ->
                let 不正 = { 観測を作る 観測者A "不正" 0.2 10L 視覚 with 確信度 = Double.NaN }
                let 候補 = 候補を作る 0.8 [] [ 不正 ]
                警戒意図生成.信念候補から作る 基本設定 候補
                |> エラー一覧を確認する [ "反証観測[0]: 観測の確信度が有限値ではありません。" ]

            testCase "設定と候補と根拠と反証のエラーを固定順で返す" <| fun _ ->
                let 空ID = エンティティID " "
                let 不正根拠 = { 観測を作る 空ID "根拠" 0.5 10L 視覚 with 概要 = "" }
                let 不正反証 = { 観測を作る 観測者B "反証" 0.5 11L 聴覚 with 確信度 = Double.NaN }

                let 候補: 信念候補 =
                    {
                        仮説 = ""
                        確率 = -0.1
                        根拠一覧 = [ 不正根拠 ]
                        反証一覧 = [ 不正反証 ]
                    }

                警戒意図生成.信念候補から作る { 発生閾値 = Double.PositiveInfinity } 候補
                |> エラー一覧を確認する
                    [
                        "警戒意図設定の発生閾値が有限値ではありません。"
                        "警戒意図設定の発生閾値は0.0以上1.0以下である必要があります。"
                        "信念候補: 信念候補の仮説が空です。"
                        "信念候補: 信念候補の確率は0.0以上1.0以下である必要があります。"
                        "根拠観測[0]: 観測の概要が空です。"
                        "反証観測[0]: 観測の確信度が有限値ではありません。"
                        "警戒意図生成に使用する観測者IDが空です。"
                        "警戒意図生成に使用する観測の観測者IDが一致しません。"
                    ]

            testCase "異なるTickの観測を許可する" <| fun _ ->
                let 第一 = 観測を作る 観測者A "Tick10" 0.8 10L 視覚
                let 第二 = 観測を作る 観測者A "Tick20" 0.2 20L 視覚
                let 候補 = 候補を作る 0.8 [ 第一 ] [ 第二 ]
                警戒意図生成.信念候補から作る 基本設定 候補 |> 意図を得る |> ignore

            testCase "異なる感知種別の観測を許可する" <| fun _ ->
                let 視覚観測 = 観測を作る 観測者A "視覚" 0.8 10L 視覚
                let 嗅覚観測 = 観測を作る 観測者A "嗅覚" 0.2 10L 嗅覚
                let 候補 = 候補を作る 0.8 [ 視覚観測 ] [ 嗅覚観測 ]
                警戒意図生成.信念候補から作る 基本設定 候補 |> 意図を得る |> ignore

            testCase "根拠と反証の入力順と重複を維持する" <| fun _ ->
                let 第一 = 観測を作る 観測者A "第一" 0.8 10L 視覚
                let 第二 = 観測を作る 観測者A "第二" 0.2 11L 聴覚
                let 候補 = 候補を作る 0.8 [ 第二; 第一; 第二 ] [ 第一; 第一 ]
                let 意図 = 警戒意図生成.信念候補から作る 基本設定 候補 |> 意図を得る
                Expect.equal 意図.由来信念候補.根拠一覧 候補.根拠一覧 "根拠順と重複を保つ"
                Expect.equal 意図.由来信念候補.反証一覧 候補.反証一覧 "反証順と重複を保つ"

            testCase "入力値を変更しない" <| fun _ ->
                let 設定 = 基本設定
                let 候補 = 基本候補
                let 設定前 = 設定
                let 候補前 = 候補
                警戒意図生成.信念候補から作る 設定 候補 |> ignore
                Expect.equal 設定 設定前 "設定を変更しない"
                Expect.equal 候補 候補前 "候補を変更しない"

            testCase "同じ入力から同じ結果を返す" <| fun _ ->
                let 第一 = 警戒意図生成.信念候補から作る 基本設定 基本候補
                let 第二 = 警戒意図生成.信念候補から作る 基本設定 基本候補
                Expect.equal 第一 第二 "構造的に同じ結果を返す"

            testCase "信念候補生成で作った候補から意図を生成できる" <| fun _ ->
                let 根拠 = 観測を作る 観測者A "根拠" 1.0 10L 視覚

                let 候補 =
                    match 信念候補生成.観測から作る "危険がある" 0.5 [ 根拠 ] [] with
                    | Ok 値 -> 値
                    | Error エラー一覧 -> failtestf "信念候補生成に失敗しました: %A" エラー一覧

                警戒意図生成.信念候補から作る { 発生閾値 = 0.75 } 候補 |> 意図を得る |> ignore

            testCase "伝播信号から警戒意図までの標準認識経路を接続できる" <| fun _ ->
                let 感知設定: 感知設定 =
                    {
                        種別 = 地盤感知
                        対象量種別 = 地盤振動
                        対象媒体 = 地盤
                        最大距離 = 10.0
                        感度倍率 = 1.0
                        感知閾値 = 0.0
                        確信飽和値 = 10.0
                    }

                let 信号: 伝播信号 =
                    {
                        ID = 伝播信号ID "signal.alert"
                        原因因果ID = None
                        発生源EntityID = None
                        量種別 = 地盤振動
                        媒体 = 地盤
                        発生位置 = { X = 0.0; Y = 0.0 }
                        方向 = None
                        強度 = 10.0
                        方式 = 波動
                        寿命Tick = 1L
                    }

                let 感知 =
                    match 感知値生成.伝播信号から作る 30L 観測者A 信号.発生位置 感知設定 信号 with
                    | Ok(Some 値) -> 値
                    | 結果 -> failtestf "感知値生成に失敗しました: %A" 結果

                let 観測 =
                    match 観測生成.感知値から観測を作る "強い地盤振動" [ 感知 ] with
                    | Ok 値 -> 値
                    | Error エラー一覧 -> failtestf "観測生成に失敗しました: %A" エラー一覧

                let 候補 =
                    match 信念候補生成.観測から作る "大型Entityが接近中" 0.5 [ 観測 ] [] with
                    | Ok 値 -> 値
                    | Error エラー一覧 -> failtestf "信念候補生成に失敗しました: %A" エラー一覧

                let 意図 = 警戒意図生成.信念候補から作る { 発生閾値 = 0.75 } 候補 |> 意図を得る
                Expect.equal 意図.観測者ID 観測者A "世界状態なしで観測者固有の意図へ接続する"
                Expect.equal 意図.対象仮説 "大型Entityが接近中" "標準認識経路の仮説を保持する"
        ]
