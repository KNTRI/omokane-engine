module SensingTests

open System
open Expecto
open Omokane.Core.Domain

let private 観測者 = エンティティID "observer.sensing"

let private 基本設定: 感知設定 =
    {
        種別 = 地盤感知
        対象量種別 = 地盤振動
        対象媒体 = 地盤
        最大距離 = 10.0
        感度倍率 = 1.0
        感知閾値 = 1.0
        確信飽和値 = 9.0
    }

let private 基本信号: 伝播信号 =
    {
        ID = 伝播信号ID "signal.sensing"
        原因因果ID = None
        発生源EntityID = None
        量種別 = 地盤振動
        媒体 = 地盤
        発生位置 = { X = 0.0; Y = 0.0 }
        方向 = None
        強度 = 10.0
        方式 = 波動
        寿命Tick = 10L
    }

let private 生成する 観測位置 設定 信号 =
    感知値生成.伝播信号から作る 20L 観測者 観測位置 設定 信号

let private 感知値を得る = function
    | Ok(Some 感知) -> 感知
    | Ok None -> failtest "感知成立を期待しましたが非感知でした。"
    | Error エラー一覧 -> failtestf "感知値生成が失敗しました: %A" エラー一覧

let private エラー一覧を得る = function
    | Error エラー一覧 -> エラー一覧
    | Ok 結果 -> failtestf "エラーを期待しましたが成功しました: %A" 結果

let private 非感知である 結果 =
    Expect.equal 結果 (Ok None) "正常な非感知を返す"

let private エラー一覧を確認する 期待値 結果 =
    結果
    |> エラー一覧を得る
    |> fun 実際値 -> Expect.equal 実際値 期待値 "エラー一覧が固定順である"

[<Tests>]
let 全テスト =
    testList
        "伝播信号から感知値を作る"
        [
            testCase "同一位置の信号を感知できる" <| fun _ ->
                生成する 基本信号.発生位置 基本設定 基本信号
                |> 感知値を得る
                |> ignore

            testCase "同一位置では強度と感度倍率の積が測定値になる" <| fun _ ->
                let 設定 = { 基本設定 with 感度倍率 = 2.0; 確信飽和値 = 30.0 }
                let 感知 = 生成する 基本信号.発生位置 設定 基本信号 |> 感知値を得る

                Expect.equal 感知.測定値 20.0 "距離係数1.0で強度と感度倍率を掛ける"

            testCase "最大距離の半分で線形に半減する" <| fun _ ->
                let 感知 = 生成する { X = 3.0; Y = 4.0 } 基本設定 基本信号 |> 感知値を得る

                Expect.equal 感知.測定値 5.0 "距離5、最大距離10では測定値が半減する"

            testCase "感知成立時の識別情報とTickを保存する" <| fun _ ->
                let 感知 = 生成する 基本信号.発生位置 基本設定 基本信号 |> 感知値を得る

                Expect.equal 感知.観測者ID 観測者 "観測者IDを保存する"
                Expect.equal 感知.信号ID 基本信号.ID "信号IDを保存する"
                Expect.equal 感知.種別 基本設定.種別 "感知種別を保存する"
                Expect.equal 感知.Tick 20L "現在Tickを保存する"

            testCase "閾値と飽和値の間で確信度を正規化する" <| fun _ ->
                let 設定 = { 基本設定 with 感知閾値 = 2.0; 確信飽和値 = 8.0 }
                let 信号 = { 基本信号 with 強度 = 5.0 }
                let 感知 = 生成する 信号.発生位置 設定 信号 |> 感知値を得る

                Expect.equal 感知.確信度 0.5 "閾値から飽和値までを0から1へ正規化する"

            testCase "飽和値以上で確信度が1になる" <| fun _ ->
                let 感知 = 生成する 基本信号.発生位置 基本設定 基本信号 |> 感知値を得る

                Expect.equal 感知.確信度 1.0 "飽和値以上は1.0にする"

            testCase "量種別不一致は正常な非感知になる" <| fun _ ->
                let 信号 = { 基本信号 with 量種別 = 熱 }
                生成する 信号.発生位置 基本設定 信号 |> 非感知である

            testCase "媒体不一致は正常な非感知になる" <| fun _ ->
                let 信号 = { 基本信号 with 媒体 = 大気 }
                生成する 信号.発生位置 基本設定 信号 |> 非感知である

            testCase "最大距離と等しい位置は正常な非感知になる" <| fun _ ->
                生成する { X = 10.0; Y = 0.0 } 基本設定 基本信号 |> 非感知である

            testCase "最大距離より外側は正常な非感知になる" <| fun _ ->
                生成する { X = 11.0; Y = 0.0 } 基本設定 基本信号 |> 非感知である

            testCase "測定値が閾値未満なら正常な非感知になる" <| fun _ ->
                let 信号 = { 基本信号 with 強度 = 0.5 }
                生成する 信号.発生位置 基本設定 信号 |> 非感知である

            testCase "測定値が閾値と等しければ正常な非感知になる" <| fun _ ->
                let 信号 = { 基本信号 with 強度 = 1.0 }
                生成する 信号.発生位置 基本設定 信号 |> 非感知である

            testCase "最大距離0かつ同一位置なら感知できる" <| fun _ ->
                let 設定 = { 基本設定 with 最大距離 = 0.0 }
                生成する 基本信号.発生位置 設定 基本信号 |> 感知値を得る |> ignore

            testCase "最大距離0かつ異なる位置なら正常な非感知になる" <| fun _ ->
                let 設定 = { 基本設定 with 最大距離 = 0.0 }
                生成する { X = 0.0; Y = 0.1 } 設定 基本信号 |> 非感知である

            testCase "感度倍率0なら正常な非感知になる" <| fun _ ->
                let 設定 = { 基本設定 with 感度倍率 = 0.0 }
                生成する 基本信号.発生位置 設定 基本信号 |> 非感知である

            testCase "負の現在Tickを拒否する" <| fun _ ->
                感知値生成.伝播信号から作る -1L 観測者 基本信号.発生位置 基本設定 基本信号
                |> エラー一覧を確認する [ "感知値生成の現在Tickが負です。" ]

            testCase "空白の観測者IDを拒否する" <| fun _ ->
                感知値生成.伝播信号から作る
                    20L
                    (エンティティID "  ")
                    基本信号.発生位置
                    基本設定
                    基本信号
                |> エラー一覧を確認する [ "感知値生成の観測者IDが空です。" ]

            testCase "観測位置のNaNとInfinityを固定順で拒否する" <| fun _ ->
                生成する { X = Double.NaN; Y = Double.PositiveInfinity } 基本設定 基本信号
                |> エラー一覧を確認する
                    [
                        "感知値生成の観測位置.Xが有限値ではありません。"
                        "感知値生成の観測位置.Yが有限値ではありません。"
                    ]

            testCase "感知設定の各不正値を固定順で拒否する" <| fun _ ->
                let 不正設定 =
                    {
                        基本設定 with
                            最大距離 = -1.0
                            感度倍率 = -1.0
                            感知閾値 = -1.0
                            確信飽和値 = -2.0
                    }

                感知設定.検証する 不正設定
                |> エラー一覧を確認する
                    [
                        "感知設定の最大距離が負です。"
                        "感知設定の感度倍率が負です。"
                        "感知設定の感知閾値が負です。"
                        "感知設定の確信飽和値は感知閾値より大きい必要があります。"
                    ]

                [
                    { 基本設定 with 最大距離 = Double.NaN },
                    [ "感知設定の最大距離が有限値ではありません。" ]
                    { 基本設定 with 感度倍率 = Double.PositiveInfinity },
                    [ "感知設定の感度倍率が有限値ではありません。" ]
                    { 基本設定 with 感知閾値 = Double.NegativeInfinity },
                    [ "感知設定の感知閾値が有限値ではありません。" ]
                    { 基本設定 with 確信飽和値 = Double.NaN },
                    [ "感知設定の確信飽和値が有限値ではありません。" ]
                ]
                |> List.iter (fun (設定, 期待値) ->
                    感知設定.検証する 設定 |> エラー一覧を確認する 期待値)

            testCase "既存の伝播信号検証エラーを返す" <| fun _ ->
                let 信号 =
                    {
                        基本信号 with
                            ID = 伝播信号ID " "
                            強度 = Double.NaN
                            寿命Tick = -1L
                    }

                生成する 信号.発生位置 基本設定 信号
                |> エラー一覧を確認する
                    [
                        "伝播信号IDが空です。"
                        "伝播信号の強度が有限値ではありません。"
                        "伝播信号の寿命Tickが負です。"
                    ]

            testCase "伝播信号の発生位置NaNとInfinityを拒否する" <| fun _ ->
                let 信号 =
                    { 基本信号 with 発生位置 = { X = Double.NaN; Y = Double.PositiveInfinity } }

                生成する { X = 0.0; Y = 0.0 } 基本設定 信号
                |> エラー一覧を確認する
                    [
                        "伝播信号の発生位置.Xが有限値ではありません。"
                        "伝播信号の発生位置.Yが有限値ではありません。"
                    ]

            testCase "伝播信号の方向NaNとInfinityを拒否する" <| fun _ ->
                let 信号 =
                    {
                        基本信号 with
                            方向 = Some { X = Double.NaN; Y = Double.NegativeInfinity }
                    }

                生成する 信号.発生位置 基本設定 信号
                |> エラー一覧を確認する
                    [
                        "伝播信号の方向.Xが有限値ではありません。"
                        "伝播信号の方向.Yが有限値ではありません。"
                    ]

            testCase "距離計算が非有限値なら拒否する" <| fun _ ->
                let 信号 =
                    { 基本信号 with 発生位置 = { X = -Double.MaxValue; Y = 0.0 } }

                生成する { X = Double.MaxValue; Y = 0.0 } 基本設定 信号
                |> エラー一覧を確認する [ "観測位置と伝播信号の距離が有限値ではありません。" ]

            testCase "測定計算が非有限値なら拒否する" <| fun _ ->
                let 設定 = { 基本設定 with 感度倍率 = 2.0 }
                let 信号 = { 基本信号 with 強度 = Double.MaxValue }

                生成する 信号.発生位置 設定 信号
                |> エラー一覧を確認する [ "感知値の測定計算結果が有限値ではありません。" ]

            testCase "入力値を変更しない" <| fun _ ->
                let 設定 = 基本設定
                let 信号 = 基本信号
                let 位置: 位置 = { X = 3.0; Y = 4.0 }
                let 設定前 = 設定
                let 信号前 = 信号
                let 位置前 = 位置

                生成する 位置 設定 信号 |> ignore

                Expect.equal 設定 設定前 "設定を変更しない"
                Expect.equal 信号 信号前 "信号を変更しない"
                Expect.equal 位置 位置前 "観測位置を変更しない"

            testCase "同じ入力から同じ結果を返す" <| fun _ ->
                let 位置: 位置 = { X = 3.0; Y = 4.0 }
                let 第一 = 生成する 位置 基本設定 基本信号
                let 第二 = 生成する 位置 基本設定 基本信号

                Expect.equal 第一 第二 "構造的に同じ結果を返す"

            testCase "生成した感知値が既存の感知値検証を通る" <| fun _ ->
                let 感知 = 生成する 基本信号.発生位置 基本設定 基本信号 |> 感知値を得る

                Expect.equal (観測検証.感知値を検証する 感知) (Ok ()) "既存契約に適合する"

            testCase "寿命Tickが0でもそれだけでは非感知にならない" <| fun _ ->
                let 信号 = { 基本信号 with 寿命Tick = 0L }
                生成する 信号.発生位置 基本設定 信号 |> 感知値を得る |> ignore

            testCase "方向と方式の違いだけでは測定値と確信度を変えない" <| fun _ ->
                let 第一 = 生成する 基本信号.発生位置 基本設定 基本信号 |> 感知値を得る

                let 別信号 =
                    {
                        基本信号 with
                            方向 = Some { X = 1.0; Y = -1.0 }
                            方式 = 拡散
                    }

                let 第二 = 生成する 別信号.発生位置 基本設定 別信号 |> 感知値を得る

                Expect.equal 第二.測定値 第一.測定値 "方向と方式を測定式に使わない"
                Expect.equal 第二.確信度 第一.確信度 "方向と方式を確信度式に使わない"

            testCase "生成した複数の感知値を既存の観測生成へ渡せる" <| fun _ ->
                let 第一信号 = { 基本信号 with ID = 伝播信号ID "signal.first"; 強度 = 5.0 }
                let 第二信号 = { 基本信号 with ID = 伝播信号ID "signal.second"; 強度 = 8.0 }
                let 設定 = { 基本設定 with 感知閾値 = 0.0; 確信飽和値 = 10.0 }
                let 第一 = 生成する 第一信号.発生位置 設定 第一信号 |> 感知値を得る
                let 第二 = 生成する 第二信号.発生位置 設定 第二信号 |> 感知値を得る

                match 観測生成.感知値から観測を作る "地盤振動を観測" [ 第一; 第二 ] with
                | Error エラー一覧 ->
                    failtestf "観測生成が失敗しました: %A" エラー一覧
                | Ok 対象観測 ->
                    Expect.equal 対象観測.根拠一覧 [ 第一; 第二 ] "生成順を根拠順として維持する"
                    Expect.equal 対象観測.確信度 0.5 "根拠の最小確信度を採用する"
        ]
