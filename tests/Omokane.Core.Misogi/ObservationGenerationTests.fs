module ObservationGenerationTests

open System
open Expecto
open Omokane.Core.Domain

let private 観測者A = エンティティID "observer.a"
let private 観測者B = エンティティID "observer.b"

let private 感知値を作る (信号ID: string) : 感知値 =
    {
        観測者ID = 観測者A
        信号ID = 伝播信号ID 信号ID
        種別 = 視覚
        測定値 = 0.5
        確信度 = 0.8
        Tick = 10L
    }

let private 観測を得る = function
    | Ok 対象観測 ->
        対象観測
    | Error エラー一覧 ->
        failtestf "観測生成が失敗しました: %A" エラー一覧

let private エラー一覧を得る = function
    | Error エラー一覧 ->
        エラー一覧
    | Ok 対象観測 ->
        failtestf "観測生成が成功しました: %A" 対象観測

let private エラー一覧を確認する 期待値 結果 =
    結果
    |> エラー一覧を得る
    |> fun 実際値 -> Expect.equal 実際値 期待値 "エラー一覧が仕様どおりである"

[<Tests>]
let 全テスト =
    testList
        "感知値から観測を作る"
        [
            testCase "1件の正常な感知値から観測を作れる" <| fun _ ->
                let 感知 = 感知値を作る "signal.1"
                let 実際 = 観測生成.感知値から観測を作る "単一観測" [ 感知 ] |> 観測を得る

                let 期待値: 観測 =
                    {
                        観測者ID = 観測者A
                        概要 = "単一観測"
                        確信度 = 0.8
                        根拠一覧 = [ 感知 ]
                    }

                Expect.equal 実際 期待値 "1件の感知値を観測へ変換できる"

            testCase "2件の正常な感知値から観測を作れる" <| fun _ ->
                let 第一 = 感知値を作る "signal.1"
                let 第二 = { 感知値を作る "signal.2" with 測定値 = 0.4 }
                let 実際 = 観測生成.感知値から観測を作る "複数観測" [ 第一; 第二 ] |> 観測を得る

                Expect.equal 実際.根拠一覧.Length 2 "2件を1つの観測へまとめられる"

            testCase "確信度0.8と0.6から0.6が選ばれる" <| fun _ ->
                let 第一 = 感知値を作る "signal.1"
                let 第二 = { 感知値を作る "signal.2" with 確信度 = 0.6 }
                let 実際 = 観測生成.感知値から観測を作る "確信度集約" [ 第一; 第二 ] |> 観測を得る

                Expect.equal 実際.確信度 0.6 "最小確信度を採用する"

            testCase "根拠一覧の入力順が保持される" <| fun _ ->
                let 第一 = 感知値を作る "signal.first"
                let 第二 = 感知値を作る "signal.second"
                let 入力 = [ 第二; 第一 ]
                let 実際 = 観測生成.感知値から観測を作る "順序確認" 入力 |> 観測を得る

                Expect.equal 実際.根拠一覧 入力 "入力順を並べ替えない"

            testCase "同じ入力から構造的に同じ観測を返す" <| fun _ ->
                let 入力 = [ 感知値を作る "signal.1"; 感知値を作る "signal.2" ]
                let 第一結果 = 観測生成.感知値から観測を作る "決定論" 入力
                let 第二結果 = 観測生成.感知値から観測を作る "決定論" 入力

                Expect.equal 第一結果 第二結果 "同じ入力から同じ結果を返す"

            testCase "null概要は失敗する" <| fun _ ->
                観測生成.感知値から観測を作る null [ 感知値を作る "signal.1" ]
                |> エラー一覧を確認する [ "観測の概要が空です。" ]

            testCase "空文字概要は失敗する" <| fun _ ->
                観測生成.感知値から観測を作る "" [ 感知値を作る "signal.1" ]
                |> エラー一覧を確認する [ "観測の概要が空です。" ]

            testCase "空白だけの概要は失敗する" <| fun _ ->
                観測生成.感知値から観測を作る "   " [ 感知値を作る "signal.1" ]
                |> エラー一覧を確認する [ "観測の概要が空です。" ]

            testCase "空一覧は失敗する" <| fun _ ->
                観測生成.感知値から観測を作る "空一覧" []
                |> エラー一覧を確認する [ "感知値一覧が空です。" ]

            testCase "観測者ID不一致は失敗する" <| fun _ ->
                let 第一 = 感知値を作る "signal.1"
                let 第二 = { 感知値を作る "signal.2" with 観測者ID = 観測者B }

                観測生成.感知値から観測を作る "観測者不一致" [ 第一; 第二 ]
                |> エラー一覧を確認する [ "感知値一覧の観測者IDが一致しません。" ]

            testCase "Tick不一致は失敗する" <| fun _ ->
                let 第一 = 感知値を作る "signal.1"
                let 第二 = { 感知値を作る "signal.2" with Tick = 11L }

                観測生成.感知値から観測を作る "Tick不一致" [ 第一; 第二 ]
                |> エラー一覧を確認する [ "感知値一覧のTickが一致しません。" ]

            testCase "感知種別不一致は失敗する" <| fun _ ->
                let 第一 = 感知値を作る "signal.1"
                let 第二 = { 感知値を作る "signal.2" with 種別 = 聴覚 }

                観測生成.感知値から観測を作る "感知種別不一致" [ 第一; 第二 ]
                |> エラー一覧を確認する [ "感知値一覧の感知種別が一致しません。" ]

            testCase "負のTickは失敗する" <| fun _ ->
                let 不正値 = { 感知値を作る "signal.1" with Tick = -1L }

                観測生成.感知値から観測を作る "負のTick" [ 不正値 ]
                |> エラー一覧を確認する [ "感知値[0]: 感知値のTickが負です。" ]

            testCase "測定値NaNは失敗する" <| fun _ ->
                let 不正値 = { 感知値を作る "signal.1" with 測定値 = Double.NaN }

                観測生成.感知値から観測を作る "NaN" [ 不正値 ]
                |> エラー一覧を確認する [ "感知値[0]: 感知値の測定値が有限値ではありません。" ]

            testCase "測定値PositiveInfinityは失敗する" <| fun _ ->
                let 不正値 = { 感知値を作る "signal.1" with 測定値 = Double.PositiveInfinity }

                観測生成.感知値から観測を作る "正の無限大" [ 不正値 ]
                |> エラー一覧を確認する [ "感知値[0]: 感知値の測定値が有限値ではありません。" ]

            testCase "測定値NegativeInfinityは失敗する" <| fun _ ->
                let 不正値 = { 感知値を作る "signal.1" with 測定値 = Double.NegativeInfinity }

                観測生成.感知値から観測を作る "負の無限大" [ 不正値 ]
                |> エラー一覧を確認する [ "感知値[0]: 感知値の測定値が有限値ではありません。" ]

            testCase "確信度が負なら失敗する" <| fun _ ->
                let 不正値 = { 感知値を作る "signal.1" with 確信度 = -0.1 }

                観測生成.感知値から観測を作る "負の確信度" [ 不正値 ]
                |> エラー一覧を確認する [ "感知値[0]: 感知値の確信度は0.0以上1.0以下である必要があります。" ]

            testCase "確信度が1.0を超える場合は失敗する" <| fun _ ->
                let 不正値 = { 感知値を作る "signal.1" with 確信度 = 1.1 }

                観測生成.感知値から観測を作る "過大な確信度" [ 不正値 ]
                |> エラー一覧を確認する [ "感知値[0]: 感知値の確信度は0.0以上1.0以下である必要があります。" ]

            testCase "確信度NaNは失敗する" <| fun _ ->
                let 不正値 = { 感知値を作る "signal.1" with 確信度 = Double.NaN }

                観測生成.感知値から観測を作る "NaN確信度" [ 不正値 ]
                |> エラー一覧を確認する [ "感知値[0]: 感知値の確信度が有限値ではありません。" ]

            testCase "確信度Infinityは失敗する" <| fun _ ->
                let 不正値 = { 感知値を作る "signal.1" with 確信度 = Double.PositiveInfinity }

                観測生成.感知値から観測を作る "無限大確信度" [ 不正値 ]
                |> エラー一覧を確認する
                    [
                        "感知値[0]: 感知値の確信度が有限値ではありません。"
                        "感知値[0]: 感知値の確信度は0.0以上1.0以下である必要があります。"
                    ]

            testCase "複数の不正があってもエラー順序が固定される" <| fun _ ->
                let 第一 =
                    {
                        感知値を作る "signal.1" with
                            測定値 = Double.NaN
                            確信度 = -0.1
                            Tick = -1L
                    }

                let 第二 =
                    {
                        感知値を作る "signal.2" with
                            観測者ID = 観測者B
                            種別 = 聴覚
                            測定値 = Double.PositiveInfinity
                            確信度 = Double.PositiveInfinity
                            Tick = 12L
                    }

                観測生成.感知値から観測を作る " " [ 第一; 第二 ]
                |> エラー一覧を確認する
                    [
                        "観測の概要が空です。"
                        "感知値[0]: 感知値の測定値が有限値ではありません。"
                        "感知値[0]: 感知値の確信度は0.0以上1.0以下である必要があります。"
                        "感知値[0]: 感知値のTickが負です。"
                        "感知値[1]: 感知値の測定値が有限値ではありません。"
                        "感知値[1]: 感知値の確信度が有限値ではありません。"
                        "感知値[1]: 感知値の確信度は0.0以上1.0以下である必要があります。"
                        "感知値一覧の観測者IDが一致しません。"
                        "感知値一覧のTickが一致しません。"
                        "感知値一覧の感知種別が一致しません。"
                    ]

            testCase "概要と空一覧のエラー順序が固定される" <| fun _ ->
                観測生成.感知値から観測を作る " " []
                |> エラー一覧を確認する
                    [
                        "観測の概要が空です。"
                        "感知値一覧が空です。"
                    ]

            testCase "変換後も入力一覧は構造的に同じである" <| fun _ ->
                let 入力 = [ 感知値を作る "signal.1"; 感知値を作る "signal.2" ]
                let 変換前 = 入力
                観測生成.感知値から観測を作る "副作用境界" 入力 |> ignore

                Expect.equal 入力 変換前 "純粋変換は入力一覧を変更しない"
        ]
