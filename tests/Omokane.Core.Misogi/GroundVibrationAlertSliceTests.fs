module GroundVibrationAlertSliceTests

open System
open Expecto
open Omokane.Core.Domain

let private 観測者 = エンティティID "observer.ground-vibration"

let private 基本感知設定: 感知設定 =
    {
        種別 = 地盤感知
        対象量種別 = 地盤振動
        対象媒体 = 地盤
        最大距離 = 10.0
        感度倍率 = 1.0
        感知閾値 = 0.0
        確信飽和値 = 10.0
    }

let private 基本信号: 伝播信号 =
    {
        ID = 伝播信号ID "signal.ground-vibration"
        原因因果ID = None
        発生源EntityID = None
        量種別 = 地盤振動
        媒体 = 地盤
        発生位置 = { X = 0.0; Y = 0.0 }
        方向 = None
        強度 = 10.0
        方式 = 波動
        寿命Tick = 10L
    }

let private 基本入力: 地盤振動警戒入力 =
    {
        現在Tick = 30L
        観測者ID = 観測者
        観測位置 = { X = 0.0; Y = 0.0 }
        感知設定 = 基本感知設定
        信号 = 基本信号
        観測概要 = "強い地盤振動"
        仮説 = "大型Entityが接近中"
        事前確率 = 0.5
        警戒設定 = { 発生閾値 = 0.75 }
    }

let private 成立結果を得る = function
    | Ok(警戒成立(感知, 観測, 候補, 意図)) ->
        感知, 観測, 候補, 意図
    | Ok 結果 ->
        failtestf "警戒成立を期待しました: %A" 結果
    | Error エラー一覧 ->
        failtestf "地盤振動警戒経路が失敗しました: %A" エラー一覧

let private 不成立結果を得る = function
    | Ok(警戒不成立(感知, 観測, 候補)) ->
        感知, 観測, 候補
    | Ok 結果 ->
        failtestf "警戒不成立を期待しました: %A" 結果
    | Error エラー一覧 ->
        failtestf "地盤振動警戒経路が失敗しました: %A" エラー一覧

let private 非感知を確認する = function
    | Ok 非感知 -> ()
    | 結果 -> failtestf "非感知を期待しました: %A" 結果

let private エラー一覧を確認する 期待値 = function
    | Error エラー一覧 -> Expect.equal エラー一覧 期待値 "エラー一覧が固定順である"
    | Ok 結果 -> failtestf "エラーを期待しました: %A" 結果

[<Tests>]
let 全テスト =
    testList
        "地盤振動から警戒意図までの技術垂直スライス"
        [
            testCase "強い同一位置の地盤振動から警戒成立まで到達する" <| fun _ ->
                地盤振動警戒経路.実行する 基本入力 |> 成立結果を得る |> ignore

            testCase "感知測定値が10になる" <| fun _ ->
                let 感知, _, _, _ = 地盤振動警戒経路.実行する 基本入力 |> 成立結果を得る
                Expect.equal 感知.測定値 10.0 "既存感知式の測定値を保持する"

            testCase "感知確信度が1になる" <| fun _ ->
                let 感知, _, _, _ = 地盤振動警戒経路.実行する 基本入力 |> 成立結果を得る
                Expect.equal 感知.確信度 1.0 "飽和した確信度を保持する"

            testCase "観測確信度が1になる" <| fun _ ->
                let _, 観測, _, _ = 地盤振動警戒経路.実行する 基本入力 |> 成立結果を得る
                Expect.equal 観測.確信度 1.0 "感知値から生成された確信度を保持する"

            testCase "信念候補確率が0.75になる" <| fun _ ->
                let _, _, 候補, _ = 地盤振動警戒経路.実行する 基本入力 |> 成立結果を得る
                Expect.equal 候補.確率 0.75 "既存の軟証拠集約式を使う"

            testCase "警戒閾値0.75との等値で成立する" <| fun _ ->
                let _, _, 候補, 意図 = 地盤振動警戒経路.実行する 基本入力 |> 成立結果を得る
                Expect.equal 候補.確率 基本入力.警戒設定.発生閾値 "等値を成立側とする"
                Expect.equal 意図.警戒度 0.75 "候補確率を警戒度に保持する"

            testCase "観測者IDが全段階で一致する" <| fun _ ->
                let 感知, 観測, _, 意図 = 地盤振動警戒経路.実行する 基本入力 |> 成立結果を得る
                Expect.equal 感知.観測者ID 観測者 "感知値の観測者ID"
                Expect.equal 観測.観測者ID 観測者 "観測の観測者ID"
                Expect.equal 意図.観測者ID 観測者 "警戒意図の観測者ID"

            testCase "信号IDが感知値へ保存される" <| fun _ ->
                let 感知, _, _, _ = 地盤振動警戒経路.実行する 基本入力 |> 成立結果を得る
                Expect.equal 感知.信号ID 基本信号.ID "入力信号IDを変更しない"

            testCase "現在Tickが感知値へ保存される" <| fun _ ->
                let 感知, _, _, _ = 地盤振動警戒経路.実行する 基本入力 |> 成立結果を得る
                Expect.equal 感知.Tick 基本入力.現在Tick "入力Tickを保存する"

            testCase "観測概要を変更せず保存する" <| fun _ ->
                let _, 観測, _, _ = 地盤振動警戒経路.実行する 基本入力 |> 成立結果を得る
                Expect.equal 観測.概要 基本入力.観測概要 "概要を解析しない"

            testCase "仮説を候補と意図へ変更せず保存する" <| fun _ ->
                let _, _, 候補, 意図 = 地盤振動警戒経路.実行する 基本入力 |> 成立結果を得る
                Expect.equal 候補.仮説 基本入力.仮説 "候補の仮説"
                Expect.equal 意図.対象仮説 基本入力.仮説 "意図の対象仮説"

            testCase "感知したが警戒閾値未満なら警戒不成立になる" <| fun _ ->
                let 入力 = { 基本入力 with 警戒設定 = { 発生閾値 = 0.8 } }
                地盤振動警戒経路.実行する 入力 |> 不成立結果を得る |> ignore

            testCase "警戒不成立でも中間結果を返す" <| fun _ ->
                let 入力 = { 基本入力 with 警戒設定 = { 発生閾値 = 0.8 } }
                let 感知, 観測, 候補 = 地盤振動警戒経路.実行する 入力 |> 不成立結果を得る
                Expect.equal 感知.測定値 10.0 "感知値を返す"
                Expect.equal 観測.概要 入力.観測概要 "観測を返す"
                Expect.equal 候補.確率 0.75 "信念候補を返す"

            testCase "距離範囲外は非感知になる" <| fun _ ->
                let 入力 = { 基本入力 with 観測位置 = { X = 10.0; Y = 0.0 } }
                地盤振動警戒経路.実行する 入力 |> 非感知を確認する

            testCase "測定値が感知閾値以下なら非感知になる" <| fun _ ->
                let 設定 = { 基本感知設定 with 感知閾値 = 10.0; 確信飽和値 = 11.0 }
                let 入力 = { 基本入力 with 感知設定 = 設定 }
                地盤振動警戒経路.実行する 入力 |> 非感知を確認する

            testCase "感知設定の種別が地盤感知でなければ拒否する" <| fun _ ->
                let 設定 = { 基本感知設定 with 種別 = 視覚 }
                地盤振動警戒経路.実行する { 基本入力 with 感知設定 = 設定 }
                |> エラー一覧を確認する [ "地盤振動警戒入力の感知種別が地盤感知ではありません。" ]

            testCase "感知設定の対象量種別不一致を拒否する" <| fun _ ->
                let 設定 = { 基本感知設定 with 対象量種別 = 熱 }
                地盤振動警戒経路.実行する { 基本入力 with 感知設定 = 設定 }
                |> エラー一覧を確認する [ "地盤振動警戒入力の対象量種別が地盤振動ではありません。" ]

            testCase "感知設定の対象媒体不一致を拒否する" <| fun _ ->
                let 設定 = { 基本感知設定 with 対象媒体 = 大気 }
                地盤振動警戒経路.実行する { 基本入力 with 感知設定 = 設定 }
                |> エラー一覧を確認する [ "地盤振動警戒入力の対象媒体が地盤ではありません。" ]

            testCase "信号の量種別不一致を拒否する" <| fun _ ->
                let 信号 = { 基本信号 with 量種別 = 熱 }
                地盤振動警戒経路.実行する { 基本入力 with 信号 = 信号 }
                |> エラー一覧を確認する [ "地盤振動警戒入力の信号量種別が地盤振動ではありません。" ]

            testCase "信号の媒体不一致を拒否する" <| fun _ ->
                let 信号 = { 基本信号 with 媒体 = 大気 }
                地盤振動警戒経路.実行する { 基本入力 with 信号 = 信号 }
                |> エラー一覧を確認する [ "地盤振動警戒入力の信号媒体が地盤ではありません。" ]

            testCase "現在Tickと観測者IDと観測位置の不正を固定順で返す" <| fun _ ->
                let 入力 =
                    {
                        基本入力 with
                            現在Tick = -1L
                            観測者ID = エンティティID "  "
                            観測位置 = { X = Double.NaN; Y = Double.PositiveInfinity }
                    }

                地盤振動警戒入力.検証する 入力
                |> エラー一覧を確認する
                    [
                        "地盤振動警戒入力の現在Tickが負です。"
                        "地盤振動警戒入力の観測者IDが空です。"
                        "地盤振動警戒入力の観測位置.Xが有限値ではありません。"
                        "地盤振動警戒入力の観測位置.Yが有限値ではありません。"
                    ]

            testCase "感知設定と伝播信号の既存エラーを固定順で返す" <| fun _ ->
                let 設定 = { 基本感知設定 with 最大距離 = -1.0 }
                let 信号 = { 基本信号 with ID = 伝播信号ID ""; 寿命Tick = -1L }
                let 入力 = { 基本入力 with 感知設定 = 設定; 信号 = 信号 }

                地盤振動警戒入力.検証する 入力
                |> エラー一覧を確認する
                    [
                        "感知設定の最大距離が負です。"
                        "伝播信号IDが空です。"
                        "伝播信号の寿命Tickが負です。"
                    ]

            testCase "観測概要と仮説と事前確率と警戒設定の不正を固定順で返す" <| fun _ ->
                let 入力 =
                    {
                        基本入力 with
                            観測概要 = " "
                            仮説 = ""
                            事前確率 = Double.PositiveInfinity
                            警戒設定 = { 発生閾値 = Double.PositiveInfinity }
                    }

                地盤振動警戒入力.検証する 入力
                |> エラー一覧を確認する
                    [
                        "地盤振動警戒入力の観測概要が空です。"
                        "地盤振動警戒入力の仮説が空です。"
                        "地盤振動警戒入力の事前確率が有限値ではありません。"
                        "地盤振動警戒入力の事前確率は0.0以上1.0以下である必要があります。"
                        "警戒意図設定の発生閾値が有限値ではありません。"
                        "警戒意図設定の発生閾値は0.0以上1.0以下である必要があります。"
                    ]

            testCase "非感知距離でも不正設定を先に拒否する" <| fun _ ->
                let 設定 = { 基本感知設定 with 最大距離 = -1.0 }
                let 入力 = { 基本入力 with 観測位置 = { X = 100.0; Y = 0.0 }; 感知設定 = 設定 }
                地盤振動警戒経路.実行する 入力
                |> エラー一覧を確認する [ "感知設定の最大距離が負です。" ]

            testCase "感知計算の非有限結果へ感知段階接頭辞を付ける" <| fun _ ->
                let 設定 = { 基本感知設定 with 感度倍率 = 2.0 }
                let 信号 = { 基本信号 with 強度 = Double.MaxValue }
                let 入力 = { 基本入力 with 感知設定 = 設定; 信号 = 信号 }
                地盤振動警戒経路.実行する 入力
                |> エラー一覧を確認する [ "感知段階: 感知値の測定計算結果が有限値ではありません。" ]

            testCase "入力値を変更しない" <| fun _ ->
                let 入力 = 基本入力
                let 実行前 = 入力
                地盤振動警戒経路.実行する 入力 |> ignore
                Expect.equal 入力 実行前 "入力を変更しない"

            testCase "同じ入力から同じ結果を返す" <| fun _ ->
                let 第一 = 地盤振動警戒経路.実行する 基本入力
                let 第二 = 地盤振動警戒経路.実行する 基本入力
                Expect.equal 第一 第二 "構造的に同じ結果を返す"

            testCase "方向と伝播方式と寿命Tickの違いだけでは同じ警戒結果になる" <| fun _ ->
                let 第一 = 地盤振動警戒経路.実行する 基本入力

                let 別信号 =
                    {
                        基本信号 with
                            方向 = Some { X = 1.0; Y = -1.0 }
                            方式 = 伝導
                            寿命Tick = 0L
                    }

                let 第二 = 地盤振動警戒経路.実行する { 基本入力 with 信号 = 別信号 }
                Expect.equal 第一 第二 "Phase 1で未使用の信号情報へ依存しない"

            testCase "ゲーム状態を使わず標準認識経路を完走する" <| fun _ ->
                let _, 観測, 候補, 意図 = 地盤振動警戒経路.実行する 基本入力 |> 成立結果を得る
                Expect.equal 観測.根拠一覧.Length 1 "1件の感知値を観測根拠にする"
                Expect.equal 候補.根拠一覧 [ 観測 ] "1件の観測を信念根拠にする"
                Expect.equal 意図.由来信念候補 候補 "警戒意図へ候補をそのまま渡す"
        ]
