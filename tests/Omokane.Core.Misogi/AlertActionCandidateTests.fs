module AlertActionCandidateTests

open System
open Expecto
open Omokane.Core.Domain

let private 観測者A = エンティティID "observer.action.a"
let private 観測者B = エンティティID "observer.action.b"
let private 基本候補ID = 行動候補ID "action.alert.in-place"

let private 感知値を作る 観測者 信号ID 種別 確信度 Tick : 感知値 =
    {
        観測者ID = 観測者
        信号ID = 伝播信号ID 信号ID
        種別 = 種別
        測定値 = 1.0
        確信度 = 確信度
        Tick = Tick
    }

let private 観測を作る 観測者 概要 確信度 Tick 種別 : 観測 =
    {
        観測者ID = 観測者
        概要 = 概要
        確信度 = 確信度
        根拠一覧 = [ 感知値を作る 観測者 (概要 + ".signal") 種別 確信度 Tick ]
    }

let private 基本観測 = 観測を作る 観測者A "強い地盤振動" 1.0 30L 地盤感知

let private 基本信念候補: 信念候補 =
    {
        仮説 = "大型Entityが接近中"
        確率 = 0.75
        根拠一覧 = [ 基本観測 ]
        反証一覧 = []
    }

let private 基本警戒意図: 警戒意図 =
    {
        観測者ID = 観測者A
        対象仮説 = 基本信念候補.仮説
        警戒度 = 基本信念候補.確率
        由来信念候補 = 基本信念候補
    }

let private 候補を得る = function
    | Ok 候補 -> 候補
    | Error エラー一覧 -> failtestf "行動候補生成が失敗しました: %A" エラー一覧

let private エラー一覧を得る = function
    | Error エラー一覧 -> エラー一覧
    | Ok 結果 -> failtestf "エラーを期待しました: %A" 結果

let private エラー一覧を確認する 期待値 結果 =
    結果
    |> エラー一覧を得る
    |> fun 実際値 -> Expect.equal 実際値 期待値 "エラー一覧が固定順である"

let private 警戒意図を生成する 候補 =
    match 警戒意図生成.信念候補から作る { 発生閾値 = 0.75 } 候補 with
    | Ok(Some 意図) -> 意図
    | 結果 -> failtestf "警戒意図生成が成立しませんでした: %A" 結果

[<Tests>]
let 全テスト =
    testList
        "警戒意図から最小行動候補を作る"
        [
            testCase "正常な警戒意図から行動候補を生成できる" <| fun _ ->
                行動候補生成.警戒意図から作る 基本候補ID 基本警戒意図 |> 候補を得る |> ignore

            testCase "明示した行動候補IDを保存する" <| fun _ ->
                let 候補 = 行動候補生成.警戒意図から作る 基本候補ID 基本警戒意図 |> 候補を得る
                Expect.equal 候補.ID 基本候補ID "IDを自動生成しない"

            testCase "実行者IDを警戒意図から保存する" <| fun _ ->
                let 候補 = 行動候補生成.警戒意図から作る 基本候補ID 基本警戒意図 |> 候補を得る
                Expect.equal 候補.実行者ID 基本警戒意図.観測者ID "観測者を実行者候補とする"

            testCase "種別がその場警戒になる" <| fun _ ->
                let 候補 = 行動候補生成.警戒意図から作る 基本候補ID 基本警戒意図 |> 候補を得る
                Expect.equal 候補.種別 行動候補種別.その場警戒 "Phase 1唯一の候補種別"

            testCase "優先度が警戒度と完全に一致する" <| fun _ ->
                let 候補 = 行動候補生成.警戒意図から作る 基本候補ID 基本警戒意図 |> 候補を得る
                Expect.equal 候補.優先度 基本警戒意図.警戒度 "優先度を再計算しない"

            testCase "対象仮説を変更せず保存する" <| fun _ ->
                let 候補 = 行動候補生成.警戒意図から作る 基本候補ID 基本警戒意図 |> 候補を得る
                Expect.equal 候補.対象仮説 基本警戒意図.対象仮説 "仮説を解析しない"

            testCase "由来警戒意図を構造的に保存する" <| fun _ ->
                let 候補 = 行動候補生成.警戒意図から作る 基本候補ID 基本警戒意図 |> 候補を得る
                Expect.equal 候補.由来警戒意図 基本警戒意図 "入力意図をそのまま保存する"

            testCase "空白IDを警戒意図エラーより先に拒否する" <| fun _ ->
                let 不正意図 = { 基本警戒意図 with 観測者ID = エンティティID " " }

                行動候補生成.警戒意図から作る (行動候補ID "") 不正意図
                |> エラー一覧を確認する
                    [
                        "行動候補IDが空です。"
                        "警戒意図: 警戒意図の観測者IDが空です。"
                        "警戒意図: 警戒意図の観測者IDが由来信念候補の観測者IDと一致しません。"
                    ]

            testCase "警戒意図の空白観測者IDを拒否する" <| fun _ ->
                let 意図 = { 基本警戒意図 with 観測者ID = エンティティID " " }
                行動候補生成.警戒意図から作る 基本候補ID 意図
                |> エラー一覧を確認する
                    [
                        "警戒意図: 警戒意図の観測者IDが空です。"
                        "警戒意図: 警戒意図の観測者IDが由来信念候補の観測者IDと一致しません。"
                    ]

            testCase "警戒意図の空白対象仮説を拒否する" <| fun _ ->
                let 意図 = { 基本警戒意図 with 対象仮説 = "" }
                行動候補生成.警戒意図から作る 基本候補ID 意図
                |> エラー一覧を確認する
                    [
                        "警戒意図: 警戒意図の対象仮説が空です。"
                        "警戒意図: 警戒意図の対象仮説が由来信念候補の仮説と一致しません。"
                    ]

            testCase "警戒度のNaNとInfinityと範囲外を拒否する" <| fun _ ->
                [ Double.NaN; Double.PositiveInfinity; -0.1; 1.1 ]
                |> List.iter (fun 警戒度 ->
                    let 意図 = { 基本警戒意図 with 警戒度 = 警戒度 }
                    let エラー一覧 = 警戒意図.検証する 意図 |> エラー一覧を得る
                    Expect.isNonEmpty エラー一覧 "不正な警戒度を拒否する")

            testCase "不正な由来信念候補へ接頭辞付きエラーを返す" <| fun _ ->
                let 由来 = { 基本信念候補 with 確率 = Double.NaN }
                let 意図 = { 基本警戒意図 with 由来信念候補 = 由来 }

                警戒意図.検証する 意図
                |> エラー一覧を確認する
                    [
                        "由来信念候補: 信念候補の確率が有限値ではありません。"
                        "警戒意図の警戒度が由来信念候補の確率と一致しません。"
                    ]

            testCase "由来候補の観測一覧が空なら拒否する" <| fun _ ->
                let 由来 = { 基本信念候補 with 根拠一覧 = []; 反証一覧 = [] }
                let 意図 = { 基本警戒意図 with 由来信念候補 = 由来 }
                警戒意図.検証する 意図
                |> エラー一覧を確認する [ "警戒意図の由来信念候補に使用する観測一覧が空です。" ]

            testCase "不正な根拠観測へindex付きエラーを返す" <| fun _ ->
                let 不正観測 = { 基本観測 with 概要 = "" }
                let 由来 = { 基本信念候補 with 根拠一覧 = [ 不正観測 ] }
                let 意図 = { 基本警戒意図 with 由来信念候補 = 由来 }
                警戒意図.検証する 意図
                |> エラー一覧を確認する [ "根拠観測[0]: 観測の概要が空です。" ]

            testCase "不正な反証観測へindex付きエラーを返す" <| fun _ ->
                let 不正観測 = { 基本観測 with 確信度 = Double.NaN }
                let 由来 = { 基本信念候補 with 根拠一覧 = []; 反証一覧 = [ 不正観測 ] }
                let 意図 = { 基本警戒意図 with 由来信念候補 = 由来 }
                警戒意図.検証する 意図
                |> エラー一覧を確認する [ "反証観測[0]: 観測の確信度が有限値ではありません。" ]

            testCase "由来候補内の空白観測者IDを拒否する" <| fun _ ->
                let 空白観測 = 観測を作る (エンティティID " ") "空白観測者" 1.0 30L 地盤感知
                let 由来 = { 基本信念候補 with 根拠一覧 = [ 空白観測 ] }
                let 意図 = { 基本警戒意図 with 由来信念候補 = 由来 }
                let エラー一覧 = 警戒意図.検証する 意図 |> エラー一覧を得る
                Expect.contains エラー一覧 "警戒意図の由来信念候補に使用する観測者IDが空です。" "空白IDを検出する"

            testCase "由来候補内の観測者ID不一致を拒否する" <| fun _ ->
                let 反証 = 観測を作る 観測者B "別主体" 0.2 31L 聴覚
                let 由来 = { 基本信念候補 with 反証一覧 = [ 反証 ] }
                let 意図 = { 基本警戒意図 with 由来信念候補 = 由来 }
                let エラー一覧 = 警戒意図.検証する 意図 |> エラー一覧を得る
                Expect.contains エラー一覧 "警戒意図の由来信念候補に使用する観測の観測者IDが一致しません。" "主体混在を拒否する"

            testCase "警戒意図と由来候補の観測者ID不一致を拒否する" <| fun _ ->
                let 意図 = { 基本警戒意図 with 観測者ID = 観測者B }
                警戒意図.検証する 意図
                |> エラー一覧を確認する [ "警戒意図の観測者IDが由来信念候補の観測者IDと一致しません。" ]

            testCase "警戒意図と由来候補の仮説不一致を拒否する" <| fun _ ->
                let 意図 = { 基本警戒意図 with 対象仮説 = "別の仮説" }
                警戒意図.検証する 意図
                |> エラー一覧を確認する [ "警戒意図の対象仮説が由来信念候補の仮説と一致しません。" ]

            testCase "警戒意図と由来候補の確率不一致を拒否する" <| fun _ ->
                let 意図 = { 基本警戒意図 with 警戒度 = 0.8 }
                警戒意図.検証する 意図
                |> エラー一覧を確認する [ "警戒意図の警戒度が由来信念候補の確率と一致しません。" ]

            testCase "行動候補の公開検証が不整合を固定順で拒否する" <| fun _ ->
                let 候補: 行動候補 =
                    {
                        ID = 行動候補ID ""
                        実行者ID = エンティティID " "
                        種別 = 行動候補種別.その場警戒
                        優先度 = Double.NaN
                        対象仮説 = ""
                        由来警戒意図 = 基本警戒意図
                    }

                行動候補.検証する 候補
                |> エラー一覧を確認する
                    [
                        "行動候補IDが空です。"
                        "行動候補の実行者IDが空です。"
                        "行動候補の優先度が有限値ではありません。"
                        "行動候補の対象仮説が空です。"
                        "行動候補の実行者IDが由来警戒意図の観測者IDと一致しません。"
                        "行動候補の対象仮説が由来警戒意図の対象仮説と一致しません。"
                        "行動候補の優先度が由来警戒意図の警戒度と一致しません。"
                    ]

            testCase "異なるTickと感知種別の観測を許可する" <| fun _ ->
                let 根拠 = 観測を作る 観測者A "視覚" 0.8 10L 視覚
                let 反証 = 観測を作る 観測者A "聴覚" 0.2 20L 聴覚
                let 由来 = { 基本信念候補 with 根拠一覧 = [ 根拠 ]; 反証一覧 = [ 反証 ] }
                let 意図 = { 基本警戒意図 with 由来信念候補 = 由来 }
                行動候補生成.警戒意図から作る 基本候補ID 意図 |> 候補を得る |> ignore

            testCase "観測順と重複を維持する" <| fun _ ->
                let 第一 = 観測を作る 観測者A "第一" 0.8 10L 視覚
                let 第二 = 観測を作る 観測者A "第二" 0.2 20L 聴覚
                let 由来 = { 基本信念候補 with 根拠一覧 = [ 第二; 第一; 第二 ]; 反証一覧 = [ 第一; 第一 ] }
                let 意図 = { 基本警戒意図 with 由来信念候補 = 由来 }
                let 候補 = 行動候補生成.警戒意図から作る 基本候補ID 意図 |> 候補を得る
                Expect.equal 候補.由来警戒意図.由来信念候補.根拠一覧 由来.根拠一覧 "根拠順と重複"
                Expect.equal 候補.由来警戒意図.由来信念候補.反証一覧 由来.反証一覧 "反証順と重複"

            testCase "入力値を変更しない" <| fun _ ->
                let ID = 基本候補ID
                let 意図 = 基本警戒意図
                let ID前 = ID
                let 意図前 = 意図
                行動候補生成.警戒意図から作る ID 意図 |> ignore
                Expect.equal ID ID前 "IDを変更しない"
                Expect.equal 意図 意図前 "意図を変更しない"

            testCase "同じ入力から同じ結果を返す" <| fun _ ->
                let 第一 = 行動候補生成.警戒意図から作る 基本候補ID 基本警戒意図
                let 第二 = 行動候補生成.警戒意図から作る 基本候補ID 基本警戒意図
                Expect.equal 第一 第二 "構造的に同じ結果"

            testCase "警戒意図生成で作った意図から候補を生成できる" <| fun _ ->
                let 意図 = 警戒意図を生成する 基本信念候補
                行動候補生成.警戒意図から作る 基本候補ID 意図 |> 候補を得る |> ignore

            testCase "地盤振動警戒経路から行動候補まで接続できる" <| fun _ ->
                let 感知設定: 感知設定 =
                    {
                        種別 = 地盤感知
                        対象量種別 = 地盤振動
                        対象媒体 = 地盤
                        最大距離 = 10.0
                        感度倍率 = 1.0
                        感知閾値 = 0.0
                        確信飽和値 = 10.0
                    }

                let 信号: 伝播信号 =
                    {
                        ID = 伝播信号ID "signal.action"
                        原因因果ID = None
                        発生源EntityID = None
                        量種別 = 地盤振動
                        媒体 = 地盤
                        発生位置 = { X = 0.0; Y = 0.0 }
                        方向 = None
                        強度 = 10.0
                        方式 = 波動
                        寿命Tick = 1L
                    }

                let 入力: 地盤振動警戒入力 =
                    {
                        現在Tick = 40L
                        観測者ID = 観測者A
                        観測位置 = 信号.発生位置
                        感知設定 = 感知設定
                        信号 = 信号
                        観測概要 = "地盤振動を観測"
                        仮説 = "大型Entityが接近中"
                        事前確率 = 0.5
                        警戒設定 = { 発生閾値 = 0.75 }
                    }

                let 意図 =
                    match 地盤振動警戒経路.実行する 入力 with
                    | Ok(警戒成立(_, _, _, 意図)) -> 意図
                    | 結果 -> failtestf "警戒成立まで到達しませんでした: %A" 結果

                let 候補 = 行動候補生成.警戒意図から作る 基本候補ID 意図 |> 候補を得る
                Expect.equal 候補.種別 行動候補種別.その場警戒 "ゲーム状態なしで候補へ接続する"
        ]
