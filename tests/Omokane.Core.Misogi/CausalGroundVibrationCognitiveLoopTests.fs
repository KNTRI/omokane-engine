module CausalGroundVibrationCognitiveLoopTests

open Expecto
open Omokane.Core.Domain

let private 発生者ID = エンティティID "loop.emitter"
let private 観測者ID = エンティティID "loop.observer"
let private 因果ID = 因果操作ID "causal.loop.vibration"
let private 信号ID = 伝播信号ID "signal.loop.vibration"
let private 候補ID = 行動候補ID "action.loop.alert"

let private entityを作る ID x y =
    {
        ID = ID
        種別 = 敵
        所有者 = 中立
        位置 = { X = x; Y = y }
        速度 = { X = 0.5; Y = -0.25 }
        当たり判定 = None
        HP = Some(HP 9)
    }

let private 基本状態 () =
    {
        Tick = 20L
        プレイヤーID = 発生者ID
        エンティティ一覧 = [ entityを作る 発生者ID 0.0 0.0; entityを作る 観測者ID 0.0 0.0 ]
        エンティティ反応状態一覧 = []
        乱数Seed = 97531
        終了状態 = None
    }

let private 基本発生操作: 地盤振動発生操作 =
    {
        因果 =
            {
                ID = 因果ID
                Tick = 20L
                種別 = 伝播信号生成
                原因因果ID = None
                実行者ID = Some 発生者ID
                対象EntityID = None
                概要 = "大型Entityが地面を踏み鳴らした"
                発行Event一覧 = [ 衝突発生(発生者ID, 観測者ID) ]
            }
        信号ID = 信号ID
        発生位置 = { X = 0.0; Y = 0.0 }
        方向 = None
        強度 = 10.0
        方式 = 波動
        寿命Tick = 5L
    }

let private 基本感知設定: 感知設定 =
    {
        種別 = 地盤感知
        対象量種別 = 地盤振動
        対象媒体 = 地盤
        最大距離 = 10.0
        感度倍率 = 1.0
        感知閾値 = 0.0
        確信飽和値 = 10.0
    }

let private 基本入力: 因果地盤振動行動入力 =
    {
        発生操作 = 基本発生操作
        観測者ID = 観測者ID
        観測位置 = { X = 0.0; Y = 0.0 }
        感知設定 = 基本感知設定
        観測概要 = "強い地盤振動を感知した"
        仮説 = "大型Entityが接近中"
        事前確率 = 0.5
        警戒設定 = { 発生閾値 = 0.75 }
        行動候補ID = 候補ID
    }

let private 行動候補成立を得る = function
    | Ok(
        因果地盤振動行動結果.行動候補成立(
            更新,
            発生記録,
            信号,
            感知,
            観測,
            信念候補,
            警戒意図,
            行動候補
        )
      ) ->
        更新, 発生記録, 信号, 感知, 観測, 信念候補, 警戒意図, 行動候補
    | 結果 -> failtestf "行動候補成立を期待しました: %A" 結果

let private 警戒不成立を得る = function
    | Ok(因果地盤振動行動結果.警戒不成立(更新, 発生記録, 信号, 感知, 観測, 信念候補)) ->
        更新, 発生記録, 信号, 感知, 観測, 信念候補
    | 結果 -> failtestf "警戒不成立を期待しました: %A" 結果

let private 非感知を得る = function
    | Ok(因果地盤振動行動結果.非感知(更新, 発生記録, 信号)) ->
        更新, 発生記録, 信号
    | 結果 -> failtestf "非感知を期待しました: %A" 結果

let private エラー一覧を得る = function
    | Error エラー一覧 -> エラー一覧
    | Ok 結果 -> failtestf "エラーを期待しました: %A" 結果

let private 認識以降を得る 結果 =
    let _, _, _, 感知, 観測, 信念候補, 警戒意図, 行動候補 = 行動候補成立を得る 結果
    感知, 観測, 信念候補, 警戒意図, 行動候補

[<Tests>]
let 全テスト =
    testList
        "正式因果から行動候補までの閉ループ"
        [
            testCase "正式因果からその場警戒候補まで完走する" <| fun _ ->
                因果地盤振動行動経路.実行する (基本状態 ()) 基本入力
                |> 行動候補成立を得る
                |> ignore

            testCase "距離範囲外は非感知へ到達する" <| fun _ ->
                let 入力 = { 基本入力 with 観測位置 = { X = 10.0; Y = 0.0 } }
                let 更新, 記録, 信号 = 因果地盤振動行動経路.実行する (基本状態 ()) 入力 |> 非感知を得る
                Expect.equal 更新.状態 (基本状態 ()) "発生結果は保持する"
                Expect.equal 記録.信号 信号 "正式信号を保持する"

            testCase "感知後に警戒閾値未満なら警戒不成立へ到達する" <| fun _ ->
                let 入力 = { 基本入力 with 警戒設定 = { 発生閾値 = 0.8 } }
                let _, _, _, 感知, 観測, 信念候補 =
                    因果地盤振動行動経路.実行する (基本状態 ()) 入力 |> 警戒不成立を得る
                Expect.equal 感知.確信度 1.0 "感知は成立"
                Expect.equal 観測.根拠一覧 [ 感知 ] "観測は成立"
                Expect.equal 信念候補.確率 0.75 "信念候補は成立"

            testCase "警戒成立後にその場警戒候補を返す" <| fun _ ->
                let _, _, _, _, _, _, _, 行動候補 =
                    因果地盤振動行動経路.実行する (基本状態 ()) 基本入力 |> 行動候補成立を得る
                Expect.equal 行動候補.種別 行動候補種別.その場警戒 "既存生成APIへ委譲する"

            testCase "因果操作IDのProvenanceを保持する" <| fun _ ->
                let _, 記録, 信号, _, _, _, _, _ =
                    因果地盤振動行動経路.実行する (基本状態 ()) 基本入力 |> 行動候補成立を得る
                Expect.equal 基本入力.発生操作.因果.ID 記録.因果操作ID "操作から記録"
                Expect.equal 信号.原因因果ID (Some 記録.因果操作ID) "記録から信号"

            testCase "実行者から発生源のProvenanceを保持する" <| fun _ ->
                let _, 記録, 信号, _, _, _, _, _ =
                    因果地盤振動行動経路.実行する (基本状態 ()) 基本入力 |> 行動候補成立を得る
                Expect.equal 基本入力.発生操作.因果.実行者ID 記録.実行者ID "操作から記録"
                Expect.equal 信号.発生源EntityID 記録.実行者ID "記録から信号"

            testCase "信号IDから感知値のProvenanceを保持する" <| fun _ ->
                let _, _, 信号, 感知, _, _, _, _ =
                    因果地盤振動行動経路.実行する (基本状態 ()) 基本入力 |> 行動候補成立を得る
                Expect.equal 基本入力.発生操作.信号ID 信号.ID "操作から信号"
                Expect.equal 感知.信号ID 信号.ID "信号から感知値"

            testCase "観測者IDを全認識段階で保持する" <| fun _ ->
                let _, _, _, 感知, 観測, _, 警戒意図, 行動候補 =
                    因果地盤振動行動経路.実行する (基本状態 ()) 基本入力 |> 行動候補成立を得る
                Expect.equal 感知.観測者ID 基本入力.観測者ID "感知"
                Expect.equal 観測.観測者ID 基本入力.観測者ID "観測"
                Expect.equal 警戒意図.観測者ID 基本入力.観測者ID "意図"
                Expect.equal 行動候補.実行者ID 基本入力.観測者ID "候補"

            testCase "仮説を信念候補と意図と行動候補へ保持する" <| fun _ ->
                let _, _, _, _, _, 信念候補, 警戒意図, 行動候補 =
                    因果地盤振動行動経路.実行する (基本状態 ()) 基本入力 |> 行動候補成立を得る
                Expect.equal 信念候補.仮説 基本入力.仮説 "信念候補"
                Expect.equal 警戒意図.対象仮説 基本入力.仮説 "警戒意図"
                Expect.equal 行動候補.対象仮説 基本入力.仮説 "行動候補"

            testCase "確率から警戒度と優先度のProvenanceを保持する" <| fun _ ->
                let _, _, _, _, _, 信念候補, 警戒意図, 行動候補 =
                    因果地盤振動行動経路.実行する (基本状態 ()) 基本入力 |> 行動候補成立を得る
                Expect.equal 警戒意図.警戒度 信念候補.確率 "確率を再計算しない"
                Expect.equal 行動候補.優先度 警戒意図.警戒度 "優先度を再計算しない"

            testCase "発生因果操作のEventだけを返す" <| fun _ ->
                let 更新, _, _, _, _, _, _, _ =
                    因果地盤振動行動経路.実行する (基本状態 ()) 基本入力 |> 行動候補成立を得る
                Expect.equal 更新.イベント一覧 基本入力.発生操作.因果.発行Event一覧 "認識由来Eventを加えない"

            testCase "認識と行動候補生成はEventを追加しない" <| fun _ ->
                let 発生操作 = { 基本発生操作 with 因果.発行Event一覧 = [] }
                let 入力 = { 基本入力 with 発生操作 = 発生操作 }
                let 更新, _, _, _, _, _, _, _ =
                    因果地盤振動行動経路.実行する (基本状態 ()) 入力 |> 行動候補成立を得る
                Expect.isEmpty 更新.イベント一覧 "後段は通知を生成しない"

            testCase "閉ループ全体でゲーム状態を変更しない" <| fun _ ->
                let 状態 = 基本状態 ()
                let 更新, _, _, _, _, _, _, _ = 因果地盤振動行動経路.実行する 状態 基本入力 |> 行動候補成立を得る
                Expect.equal 更新.状態 状態 "World Truthを変更しない"

            testCase "閉ループ全体でEntity一覧を変更しない" <| fun _ ->
                let 状態 = 基本状態 ()
                let 更新, _, _, _, _, _, _, _ = 因果地盤振動行動経路.実行する 状態 基本入力 |> 行動候補成立を得る
                Expect.equal 更新.状態.エンティティ一覧 状態.エンティティ一覧 "Entityを更新しない"

            testCase "閉ループ全体でTickを変更しない" <| fun _ ->
                let 状態 = 基本状態 ()
                let 更新, _, _, _, _, _, _, _ = 因果地盤振動行動経路.実行する 状態 基本入力 |> 行動候補成立を得る
                Expect.equal 更新.状態.Tick 状態.Tick "Tick進行を行わない"

            testCase "閉ループ全体で乱数Seedを変更しない" <| fun _ ->
                let 状態 = 基本状態 ()
                let 更新, _, _, _, _, _, _, _ = 因果地盤振動行動経路.実行する 状態 基本入力 |> 行動候補成立を得る
                Expect.equal 更新.状態.乱数Seed 状態.乱数Seed "乱数を消費しない"

            testCase "地盤振動発生段階Errorへ接頭辞を付ける" <| fun _ ->
                let 発生操作 = { 基本発生操作 with 因果.種別 = 状態変更 }
                let 入力 = { 基本入力 with 発生操作 = 発生操作 }
                let エラー一覧 = 因果地盤振動行動経路.実行する (基本状態 ()) 入力 |> エラー一覧を得る
                Expect.equal エラー一覧 [ "地盤振動発生段階: 因果操作種別が伝播信号生成ではありません。" ] "段階を示す"

            testCase "認識段階Errorへ接頭辞を付ける" <| fun _ ->
                let 設定 = { 基本感知設定 with 最大距離 = -1.0 }
                let 入力 = { 基本入力 with 感知設定 = 設定 }
                let エラー一覧 = 因果地盤振動行動経路.実行する (基本状態 ()) 入力 |> エラー一覧を得る
                Expect.equal エラー一覧 [ "認識段階: 感知設定の最大距離が負です。" ] "既存エラーを保持する"

            testCase "行動候補段階Errorへ接頭辞を付ける" <| fun _ ->
                let 入力 = { 基本入力 with 行動候補ID = 行動候補ID " " }
                let エラー一覧 = 因果地盤振動行動経路.実行する (基本状態 ()) 入力 |> エラー一覧を得る
                Expect.equal エラー一覧 [ "行動候補段階: 行動候補IDが空です。" ] "既存エラーを保持する"

            testCase "発生段階の失敗を後段入力不正より優先する" <| fun _ ->
                let 発生操作 = { 基本発生操作 with 因果.Tick = 99L }
                let 入力 = { 基本入力 with 発生操作 = 発生操作; 観測概要 = " "; 行動候補ID = 行動候補ID "" }
                let エラー一覧 = 因果地盤振動行動経路.実行する (基本状態 ()) 入力 |> エラー一覧を得る
                Expect.equal エラー一覧 [ "地盤振動発生段階: 地盤振動発生操作のTickが現在状態のTickと一致しません。" ] "固定段階順"

            testCase "方向と方式と寿命の違いはPhase1認識結果を変えない" <| fun _ ->
                let 第一 = 因果地盤振動行動経路.実行する (基本状態 ()) 基本入力 |> 認識以降を得る

                let 発生操作 =
                    {
                        基本発生操作 with
                            方向 = Some { X = 1.0; Y = -1.0 }
                            方式 = 伝導
                            寿命Tick = 0L
                    }

                let 第二入力 = { 基本入力 with 発生操作 = 発生操作 }
                let 第二 = 因果地盤振動行動経路.実行する (基本状態 ()) 第二入力 |> 認識以降を得る
                Expect.equal 第二 第一 "未使用信号情報を後段計算へ混ぜない"

            testCase "閉ループ入力を変更しない" <| fun _ ->
                let 状態 = 基本状態 ()
                let 入力 = 基本入力
                let 状態前 = 状態
                let 入力前 = 入力
                因果地盤振動行動経路.実行する 状態 入力 |> ignore
                Expect.equal 状態 状態前 "状態入力"
                Expect.equal 入力 入力前 "閉ループ入力"

            testCase "同じ入力から同じ最終結果を返す" <| fun _ ->
                let 状態 = 基本状態 ()
                Expect.equal
                    (因果地盤振動行動経路.実行する 状態 基本入力)
                    (因果地盤振動行動経路.実行する 状態 基本入力)
                    "構造的に同じ結果"

            testCase "強度距離警戒閾値Matrixが決定論的である" <| fun _ ->
                let 強度一覧 = [ 0.5; 1.0; 2.0; 5.0; 10.0; 20.0 ]
                let 距離一覧 = [ 0.0; 2.5; 5.0; 7.5; 9.0; 10.0; 11.0 ]
                let 警戒閾値一覧 = [ 0.25; 0.5; 0.75; 1.0 ]

                [
                    for 強度 in 強度一覧 do
                        for 距離 in 距離一覧 do
                            for 警戒閾値 in 警戒閾値一覧 do
                                let 発生操作 = { 基本発生操作 with 強度 = 強度 }
                                let 入力 =
                                    {
                                        基本入力 with
                                            発生操作 = 発生操作
                                            観測位置 = { X = 距離; Y = 0.0 }
                                            警戒設定 = { 発生閾値 = 警戒閾値 }
                                    }

                                let 第一 = 因果地盤振動行動経路.実行する (基本状態 ()) 入力
                                let 第二 = 因果地盤振動行動経路.実行する (基本状態 ()) 入力
                                Expect.equal 第二 第一 (sprintf "強度=%g 距離=%g 閾値=%g" 強度 距離 警戒閾値)
                ]
                |> ignore
        ]
