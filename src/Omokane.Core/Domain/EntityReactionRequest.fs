namespace Omokane.Core.Domain

type エンティティ反応要求ID =
    | エンティティ反応要求ID of string

[<RequireQualifiedAccess>]
type エンティティ反応種別 =
    | その場警戒

type エンティティ反応要求 =
    private
    | エンティティ反応要求 of
        ID: エンティティ反応要求ID *
        Tick: int64 *
        実行者ID: エンティティID *
        種別: エンティティ反応種別 *
        優先度: float *
        対象仮説: string *
        由来選択済み行動候補: 選択済み行動候補

module エンティティ反応要求 =

    let ID (エンティティ反応要求(ID, _, _, _, _, _, _)) =
        ID

    let Tick (エンティティ反応要求(_, Tick, _, _, _, _, _)) =
        Tick

    let 実行者ID (エンティティ反応要求(_, _, 実行者ID, _, _, _, _)) =
        実行者ID

    let 種別 (エンティティ反応要求(_, _, _, 種別, _, _, _)) =
        種別

    let 優先度 (エンティティ反応要求(_, _, _, _, 優先度, _, _)) =
        優先度

    let 対象仮説 (エンティティ反応要求(_, _, _, _, _, 対象仮説, _)) =
        対象仮説

    let 由来選択済み行動候補
        (エンティティ反応要求(_, _, _, _, _, _, 由来選択済み行動候補)) =
        由来選択済み行動候補

    let 由来行動候補 要求 =
        要求
        |> 由来選択済み行動候補
        |> 選択済み行動候補.選択候補

    let 由来行動候補ID 要求 =
        (由来行動候補 要求).ID

    let 由来候補一覧 要求 =
        要求
        |> 由来選択済み行動候補
        |> 選択済み行動候補.候補一覧

    let 由来選択位置 要求 =
        要求
        |> 由来選択済み行動候補
        |> 選択済み行動候補.選択位置

    let 由来却下候補一覧 要求 =
        要求
        |> 由来選択済み行動候補
        |> 選択済み行動候補.却下候補一覧

    let 由来同率最高候補一覧 要求 =
        要求
        |> 由来選択済み行動候補
        |> 選択済み行動候補.同率最高候補一覧

    let 由来選択理由 要求 =
        要求
        |> 由来選択済み行動候補
        |> 選択済み行動候補.選択理由

module エンティティ反応要求生成 =

    let 選択済み行動候補から作る
        (要求ID: エンティティ反応要求ID)
        (Tick: int64)
        (選択済み: 選択済み行動候補)
        : Result<エンティティ反応要求, string list> =
        let (エンティティ反応要求ID 要求ID値) = 要求ID

        let エラー一覧 =
            [
                if System.String.IsNullOrWhiteSpace 要求ID値 then
                    "エンティティ反応要求IDが空です。"

                if Tick < 0L then
                    "エンティティ反応要求のTickが負です。"
            ]

        if not (List.isEmpty エラー一覧) then
            Error エラー一覧
        else
            let 選択候補 = 選択済み行動候補.選択候補 選択済み

            let 反応種別 =
                match 選択候補.種別 with
                | 行動候補種別.その場警戒 -> エンティティ反応種別.その場警戒

            Ok(
                エンティティ反応要求(
                    要求ID,
                    Tick,
                    選択済み行動候補.実行者ID 選択済み,
                    反応種別,
                    選択候補.優先度,
                    選択候補.対象仮説,
                    選択済み
                )
            )
