namespace Omokane.Core.Domain

[<RequireQualifiedAccess>]
type 互換移動命令種別 =
    | 左へ移動
    | 右へ移動

type 互換移動命令 =
    private
    | 互換移動命令 of
        種別: 互換移動命令種別 *
        由来制御結果: 自発移動意図制御結果

module 互換移動命令 =

    let 種別 (互換移動命令(種別, _)) = 種別

    let 既存入力 命令 =
        match 種別 命令 with
        | 互換移動命令種別.左へ移動 -> 入力.左へ移動
        | 互換移動命令種別.右へ移動 -> 入力.右へ移動

    let 由来制御結果 (互換移動命令(_, 結果)) = 結果

    let 由来自発移動意図 命令 =
        命令 |> 由来制御結果 |> 自発移動意図制御結果.意図

    let 由来自発移動意図ID 命令 =
        命令 |> 由来自発移動意図 |> 自発移動意図.ID

    let Tick 命令 = 命令 |> 由来自発移動意図 |> 自発移動意図.Tick

    let 実行者ID 命令 = 命令 |> 由来自発移動意図 |> 自発移動意図.実行者ID

    let 由来自発移動方向 命令 = 命令 |> 由来自発移動意図 |> 自発移動意図.方向

    let 由来入力 命令 = 命令 |> 由来自発移動意図 |> 自発移動意図.由来入力

    let 由来制御判断 命令 = 命令 |> 由来制御結果 |> 自発移動意図制御結果.制御判断

    let 由来制御理由 命令 = 命令 |> 由来制御結果 |> 自発移動意図制御結果.制御理由

    let 由来反応要求ID 命令 = 命令 |> 由来制御結果 |> 自発移動意図制御結果.由来反応要求ID

    let 由来反応状態成立因果操作ID 命令 =
        命令 |> 由来制御結果 |> 自発移動意図制御結果.由来反応状態成立因果操作ID

[<RequireQualifiedAccess>]
type 互換移動非生成理由 =
    | 自発移動抑制
    | 上方向未対応
    | 下方向未対応

[<RequireQualifiedAccess>]
type 互換移動変換結果 =
    private
    | 命令生成 of 命令: 互換移動命令
    | 未生成 of 理由: 互換移動非生成理由 * 由来制御結果: 自発移動意図制御結果

module 互換移動変換結果 =

    let 由来制御結果 = function
        | 互換移動変換結果.命令生成 命令 -> 互換移動命令.由来制御結果 命令
        | 互換移動変換結果.未生成(_, 結果) -> 結果

    let 由来自発移動意図 結果 =
        結果 |> 由来制御結果 |> 自発移動意図制御結果.意図

    let 命令 = function
        | 互換移動変換結果.命令生成 命令 -> Some 命令
        | 互換移動変換結果.未生成 _ -> None

    let 既存入力 結果 = 結果 |> 命令 |> Option.map 互換移動命令.既存入力

    let 非生成理由 = function
        | 互換移動変換結果.命令生成 _ -> None
        | 互換移動変換結果.未生成(理由, _) -> Some 理由

    let 命令を生成した 結果 = 結果 |> 命令 |> Option.isSome

    let 命令を生成しなかった 結果 = 結果 |> 命令 |> Option.isNone

    let 自発移動抑制である 結果 =
        非生成理由 結果 = Some 互換移動非生成理由.自発移動抑制

    let 未対応方向 結果 =
        match 非生成理由 結果 with
        | None
        | Some 互換移動非生成理由.自発移動抑制 -> None
        | Some 互換移動非生成理由.上方向未対応 -> Some 自発移動方向.上
        | Some 互換移動非生成理由.下方向未対応 -> Some 自発移動方向.下

    let 方向未対応である 結果 = 結果 |> 未対応方向 |> Option.isSome

    let Tick 結果 = 結果 |> 由来自発移動意図 |> 自発移動意図.Tick

    let 実行者ID 結果 = 結果 |> 由来自発移動意図 |> 自発移動意図.実行者ID

    let 自発移動意図ID 結果 = 結果 |> 由来自発移動意図 |> 自発移動意図.ID

    let 自発移動方向 結果 = 結果 |> 由来自発移動意図 |> 自発移動意図.方向

    let 由来反応要求ID 結果 = 結果 |> 由来制御結果 |> 自発移動意図制御結果.由来反応要求ID

    let 由来反応状態成立因果操作ID 結果 =
        結果 |> 由来制御結果 |> 自発移動意図制御結果.由来反応状態成立因果操作ID

module 自発移動互換変換 =

    let 変換する 制御結果 =
        match 自発移動意図制御結果.通過意図 制御結果 with
        | None ->
            互換移動変換結果.未生成(互換移動非生成理由.自発移動抑制, 制御結果)
        | Some 意図 ->
            match 自発移動意図.方向 意図 with
            | 自発移動方向.左 ->
                互換移動変換結果.命令生成(互換移動命令(互換移動命令種別.左へ移動, 制御結果))
            | 自発移動方向.右 ->
                互換移動変換結果.命令生成(互換移動命令(互換移動命令種別.右へ移動, 制御結果))
            | 自発移動方向.上 ->
                互換移動変換結果.未生成(互換移動非生成理由.上方向未対応, 制御結果)
            | 自発移動方向.下 ->
                互換移動変換結果.未生成(互換移動非生成理由.下方向未対応, 制御結果)

    let 一括変換する 制御結果一覧 = List.map 変換する 制御結果一覧

module 互換移動変換結果一覧 =

    let 命令一覧 結果一覧 = List.choose 互換移動変換結果.命令 結果一覧

    let 未生成結果一覧 結果一覧 = List.filter 互換移動変換結果.命令を生成しなかった 結果一覧

    let 抑制結果一覧 結果一覧 = List.filter 互換移動変換結果.自発移動抑制である 結果一覧

    let 方向未対応結果一覧 結果一覧 = List.filter 互換移動変換結果.方向未対応である 結果一覧
