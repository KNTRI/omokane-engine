namespace Omokane.Core.Domain

[<RequireQualifiedAccess>]
type 因果地盤振動行動入力 =
    {
        発生操作: 地盤振動発生操作
        観測者ID: エンティティID
        観測位置: 位置
        感知設定: 感知設定
        観測概要: string
        仮説: string
        事前確率: float
        警戒設定: 警戒意図設定
        行動候補ID: 行動候補ID
    }

[<RequireQualifiedAccess>]
type 因果地盤振動行動結果 =
    | 非感知 of
        更新: 更新結果 *
        発生記録: 地盤振動発生記録 *
        信号: 伝播信号
    | 警戒不成立 of
        更新: 更新結果 *
        発生記録: 地盤振動発生記録 *
        信号: 伝播信号 *
        感知: 感知値 *
        観測: 観測 *
        信念候補: 信念候補
    | 行動候補成立 of
        更新: 更新結果 *
        発生記録: 地盤振動発生記録 *
        信号: 伝播信号 *
        感知: 感知値 *
        観測: 観測 *
        信念候補: 信念候補 *
        警戒意図: 警戒意図 *
        行動候補: 行動候補

module 因果地盤振動行動経路 =

    let private 段階エラーを付ける 段階名 エラー一覧 =
        エラー一覧
        |> List.map (fun エラー -> 段階名 + ": " + エラー)

    let 実行する
        (現在状態: ゲーム状態)
        (入力: 因果地盤振動行動入力)
        : Result<因果地盤振動行動結果, string list> =
        match 地盤振動発生実行.適用する 現在状態 入力.発生操作 with
        | 発生失敗(_, _, 理由一覧) ->
            Error(段階エラーを付ける "地盤振動発生段階" 理由一覧)
        | 発生成功(更新, 信号, 発生記録) ->
            let 認識入力: 地盤振動警戒入力 =
                {
                    現在Tick = 更新.状態.Tick
                    観測者ID = 入力.観測者ID
                    観測位置 = 入力.観測位置
                    感知設定 = 入力.感知設定
                    信号 = 信号
                    観測概要 = 入力.観測概要
                    仮説 = 入力.仮説
                    事前確率 = 入力.事前確率
                    警戒設定 = 入力.警戒設定
                }

            match 地盤振動警戒経路.実行する 認識入力 with
            | Error エラー一覧 ->
                Error(段階エラーを付ける "認識段階" エラー一覧)
            | Ok 非感知 ->
                Ok(因果地盤振動行動結果.非感知(更新, 発生記録, 信号))
            | Ok(警戒不成立(感知, 観測, 信念候補)) ->
                Ok(
                    因果地盤振動行動結果.警戒不成立(
                        更新,
                        発生記録,
                        信号,
                        感知,
                        観測,
                        信念候補
                    )
                )
            | Ok(警戒成立(感知, 観測, 信念候補, 警戒意図)) ->
                match 行動候補生成.警戒意図から作る 入力.行動候補ID 警戒意図 with
                | Error エラー一覧 ->
                    Error(段階エラーを付ける "行動候補段階" エラー一覧)
                | Ok 行動候補 ->
                    Ok(
                        因果地盤振動行動結果.行動候補成立(
                            更新,
                            発生記録,
                            信号,
                            感知,
                            観測,
                            信念候補,
                            警戒意図,
                            行動候補
                        )
                    )
